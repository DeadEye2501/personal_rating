<!-- Плашка сообщений: одна на всё приложение. -->
<script>
  // Сколько держится сообщение: хватает прочесть фразу и не хватает, чтобы
  // она начала мешать.
  const LINGER = 4000

  // Сообщение приходит не строкой, а своим объектом, и это не украшение.
  // Строку Svelte сличает по значению: второй такой же отказ — а отказы
  // приезжают канонической фразой — не завёл бы отсчёт заново, и с третьего
  // раза плашка не показалась бы вовсе. Молчание при этом неотличимо от
  // успеха.
  let { message = null } = $props()

  let shown = $state(false)
  // Текст остаётся здесь после ухода плашки нарочно: пустая строка в момент
  // отъезда стёрла бы надпись на середине движения.
  let last = $state('')

  // Второе сообщение заменяет первое и заводит отсчёт заново, а не встаёт в
  // очередь: свежая беда важнее прошлой.
  //
  // Признак показа здесь только пишется, но не читается, и это не мелочь:
  // прочитанный, он попал бы в зависимости эффекта, и тот перезапускал бы сам
  // себя бесконечно.
  $effect(() => {
    if (!message?.text) {
      // Сообщение сняли — плашка уезжает. Выйти отсюда раньше значило бы
      // оставить её висеть навсегда: таймер к этому мигу уже убран.
      shown = false
      return
    }
    last = message.text
    shown = true
    const timer = setTimeout(() => { shown = false }, LINGER)
    return () => clearTimeout(timer)
  })
</script>

<div class="snack neon" class:is-shown={shown} role="status" aria-live="polite">
  {last}
</div>
