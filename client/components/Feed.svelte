<!-- Список карточек, который растёт порциями и не знает своей полной длины. -->
<script>
  import Film from '$components/Film.svelte'

  // Насколько заранее просить следующую порцию. Экран с запасом: догрузка
  // обязана начаться до того, как человек упрётся в дно.
  const AHEAD = '600px'

  let { views = [], collapsed = false, expected = [], onmore, onshown,
        ...card } = $props()

  let asking = $state(false)
  // Видна ли метка дна прямо сейчас. Наблюдатель сообщает о пересечении, а не
  // о том, что оно длится: пока лента короче экрана, метка остаётся видимой, и
  // второго события не будет никогда.
  let atEnd = false

  /**
   * И догрузка, и «карточка попала в поле зрения» — один наблюдатель на два
   * дела, а не два разных средства.
   *
   * Прокрутку слушать нельзя: прокручивается `.content`, а лента внутри неё —
   * обычная колонка, и `scroll` у непрокручиваемого блока не наступает вовсе.
   * Тянуться вверх за скроллером значило бы, что компонент знает про раскладку
   * сборки. Наблюдатель этого не требует: он работает от того, что видно, а не
   * от того, что прокручивается.
   */
  function watched(node, onseen) {
    const eye = new IntersectionObserver(
      ([entry]) => onseen(entry.isIntersecting), { rootMargin: AHEAD })
    eye.observe(node)
    return { destroy: () => eye.disconnect() }
  }

  async function more() {
    // Не просим повторно, пока предыдущая порция не приехала.
    if (asking) return
    asking = true
    try {
      // Просим, пока дно видно и есть что просить. Одного запроса на событие
      // мало: приехавшая порция может не закрыть экран, а второго события не
      // будет — метка как была видна, так и осталась.
      //
      // Между витками ждём кадр: признак видимости меняет наблюдатель, а он
      // сообщает кадром. Без паузы витки идут микрозадачами, признак остаётся
      // прошлым, и лента просит лишние порции — тем больше, чем быстрее база.
      //
      // Есть ли ещё, знает тот, кто просил: у него порция и её размер. Выводить
      // это из длины списка значило бы требовать, чтобы он дописывал, а не
      // заменял, — а смена фильтра заменяет.
      while (atEnd && await onmore()) {
        await new Promise(requestAnimationFrame)
      }
    } catch (error) {
      // Отказ ленты не должен оставлять её замершей навсегда и не должен
      // улетать необработанным промисом из обработчика наблюдателя.
      console.warn('лента не догрузилась', error)
    } finally {
      asking = false
    }
  }
</script>

<div class="feed">
  {#each views as view (view.source + ' ' + view.source_id)}
    <!-- О показе сообщаем на каждое появление; один раз на карточку это делает
         тот, кто ходит через мост: там же и память о спрошенных. -->
    <div use:watched={(visible) => visible && onshown(view)}>
      <Film {view} {collapsed} {expected} {...card} />
    </div>
  {/each}
  <!-- Метка дна: попала в поле зрения — значит пора просить следующую порцию. -->
  <div class="feed__end"
       use:watched={(visible) => { atEnd = visible; if (visible) more() }}></div>
</div>
