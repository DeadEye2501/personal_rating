/* Что раздел запустил, то он и гасит при уходе. */

import { cancel } from './bridge.js'

/** Список номеров операций раздела. Класть в него номера — дело `numbered`,
 *  гасить их при уходе — дело заведённого здесь эффекта.
 *
 *  `.svelte.js` в имени обязательно: в обычном `.js` руны не разбираются, и
 *  `$effect` остался бы неизвестным именем.
 *
 *  Списанный по месту, этот эффект теряет `splice` — а без него уход с раздела
 *  гасит и то, что уже отвечено, а вернувшись, гасит это второй раз. */
export function owned() {
  const ops = []
  $effect(() => () => { cancel(ops.splice(0)) })
  return ops
}
