import { svelte } from '@sveltejs/vite-plugin-svelte'
import { fileURLToPath } from 'node:url'
// Из `vitest/config`, а не из `vite`: ключ `test` витестовый, и у чужого
// `defineConfig` он проходит лишь потому, что Vite не выбрасывает незнакомое.
import { defineConfig } from 'vitest/config'

const here = (path) => fileURLToPath(new URL(path, import.meta.url))

export default defineConfig({
  plugins: [svelte()],

  // Псевдонимы объявлены не для краткости: проверка границы слоёв разбирает
  // относительные импорты и объявленные псевдонимы, а всё, что сверх этого
  // придумает сборщик, она не видит.
  //
  // Тот же список объявлен вторым местом — в `.claude/clean.json`, ключ
  // `front.aliases`. Это не дубль, а два разных читателя: здесь путь, там имя
  // слоя, и слить их нечем — `.claude/` в репозиторий не входит вовсе.
  // Разойтись они могут молча, и единственный сторож — проба хука псевдонимом
  // при заведении слоя.
  resolve: {
    alias: {
      $styles: here('./styles'),
      $components: here('./components'),
      $state: here('./state'),
      $api: here('./api'),
    },
  },

  // Кеш назван явно, потому что корень у прогона тестов не тот, что у сборки:
  // умолчание `<корень>/node_modules/.vite` при `test.root: '..'` заводило в
  // корне проекта пустой `node_modules` с одним лишь кешем внутри. Абсолютным
  // путём, а не относительным: относительный считался бы от того же
  // разъезжающегося корня.
  cacheDir: here('./node_modules/.vite'),

  // Пути относительные: страницу отдаёт свой обработчик, и абсолютный
  // `/assets/...` держался бы только пока корень остаётся корнем.
  base: './',
  // `dist` названо и на той стороне — `bridge/serve.py:WEB_ROOT` ищет ровно эту
  // папку. Разъехавшись, они дадут пустое окно без единой строки в логе.
  build: { outDir: 'dist', emptyOutDir: true },

  // Проверяется всё, что не разметка: `state/`, `api/` и те модули `app/`, куда
  // логика вынесена из `.svelte` своим файлом. Поддельный браузер тут не нужен
  // вовсе, а стоил бы ещё одной зависимости и секунд на каждом прогоне.
  //
  // Тесты лежат выше корня Vite (`client/`), поэтому корень прогона поднимается
  // на уровень: иначе разрешение путей и `server.fs.allow` ведут себя не так,
  // как для файлов внутри корня.
  //
  // Цена — два десятка строк `Failed to resolve dependency` на **первом**
  // прогоне в чистом клоне: зависимости лежат в `client/node_modules`, а корень
  // прогона выше. Прогон при этом зелёный, второй молчит. Замерено при сборке
  // с нуля 01.08.2026; строки видит ровно тот, кто собирает впервые, и читает
  // их как отказ.
  test: {
    root: '..',
    include: ['tests/web/**/*.test.js'],
    environment: 'node',
  },
})
