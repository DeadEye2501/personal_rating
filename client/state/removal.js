/* Фразы, которыми спрашивают про удаление: что пропадёт и кого это заденет. */

import { plural } from '$state/facts.js'
import { NOUNS } from '$state/kinds.js'

const TAGS = ['тег', 'тега', 'тегов']
const WEARS = ['имеет', 'имеют', 'имеют']

/** Перечисляет только непустое: «Оценка и 3 тега пропадут вместе с ней» на
 *  карточке без оценки читается как угроза потерять то, чего нет.
 *
 *  Считает состояние, а не разметка: склонение и отбор непустого — обычные
 *  функции над обычными данными, и проверяются они обычными тестами; оставь их
 *  в сборке, они не проверялись бы вовсе. */
export function question(view, summary) {
  const parts = []
  if (summary.has_rating) parts.push({ text: 'оценка', many: false })
  // Своим словом, хотя в базе они одной строкой: у карточки без оценки одна
  // «Оценка» соврала бы дважды — обещала бы потерю того, чего нет, и умолчала
  // бы о том, что пропадёт.
  if (summary.has_review) parts.push({ text: 'рецензия', many: false })
  if (summary.tags) {
    // Число глагола берётся тем же выбором, что и форма слова: «21 тег» больше
    // единицы, а по-русски он единственного числа, и `tags > 1` дало бы
    // «21 тег пропадут».
    parts.push({ text: `${summary.tags} ${plural(summary.tags, TAGS)}`,
                 many: plural(summary.tags, [false, true, true]) })
  }
  if (summary.in_wishlist) parts.push({ text: 'закладка', many: false })

  if (!parts.length) return `Удалить «${view.title}»?`

  // Число глагола: «Оценка пропадёт», но «Оценка и закладка пропадут» и «3 тега
  // пропадут». Одно перечисленное во множественном числе делает множественным и
  // глагол, поэтому решает не длина списка сама по себе.
  const many = parts.length > 1 || parts[0].many
  return `Удалить «${view.title}»? ${upper(listed(parts.map((part) => part.text)))}`
    + ` ${many ? 'пропадут' : 'пропадёт'} вместе с ней.`
}

/** Перечисление начинает новое предложение, а первым в нём бывает любое из
 *  четырёх: рецензия и закладка идут с прописной, только когда стоят первыми.
 *  Числу тегов прописная не достаётся — там цифра. */
const upper = (text) => text.charAt(0).toUpperCase() + text.slice(1)

/** Носители называются по открытой вкладке: набор тегов у каждого типа
 *  содержимого свой, и «3 игры имеют этот тег» во вкладке фильмов было бы
 *  ложью. Ничей тег уходит молча, и этой фразы не бывает вовсе. */
export const worn = (name, count, kind) =>
  `Удалить тег «${name}»? ${count} ${plural(count, NOUNS[kind])}`
  + ` ${plural(count, WEARS)} этот тег.`

/** Последнее присоединяется союзом, а не запятой: так в макете — «Оценка и теги
 *  пропадут вместе с ней». */
const listed = (texts) => texts.length < 2 ? texts[0]
  : `${texts.slice(0, -1).join(', ')} и ${texts.at(-1)}`
