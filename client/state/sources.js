/* Всё, что страница знает о чужом источнике: имя, шкала, адрес страницы. */

/** Не источник, а его отсутствие: так помечена карточка, заведённая руками.
 *  Отличать её нужно окну карточки — привязанной оно показывает имя источника
 *  и крестик вместо поля ссылки. */
export const MANUAL = 'manual'

/* Три таблицы, а не три модуля, потому что ключ у них один — источник, — и
 * разъехаться порознь они могут молча: седьмой источник дописали бы в одну и
 * забыли в двух. Показывает цифру одно место, красит её шкала, подписывает имя
 * и открывает адрес. */

import { stepOf } from '$state/scores.js'

/** Шкала источника. У GOG она 0–50, а не 0–5: доля положительных отзывов
 *  кладётся в базу как есть (`reviewsRating` в ответе каталога), и в записанных
 *  ответах там 46, 39, 41. С пятёркой каждая игра из GOG получала бы десятую
 *  ступень.
 *
 *  У TMDB она 0–100 — решено пользователем 02.08.2026. MDBList отдаёт её сотней,
 *  а собственный клиент TMDB приводит к сотне своё десятибалльное
 *  `vote_average`: две шкалы у одного источника ставили в ленте рядом «TMDB
 *  8.4» и «TMDB 84», означающие одно и то же. */
const MAX = { imdb: 10, kinopoisk: 10, tmdb: 100, gog: 50,
              rotten: 100, metacritic: 100, steam: 100 }

const NAMES = { imdb: 'IMDb', kinopoisk: 'Кинопоиск', tmdb: 'TMDB',
                rotten: 'Rotten Tomatoes', metacritic: 'Metacritic',
                steam: 'Steam', gog: 'GOG' }

/* Адрес есть только там, где его есть из чего собрать, и это не то же самое,
 * что «оценка приехала». Оценок семь, а собираемых адресов два:
 *
 * - у Rotten и Metacritic идентификатора нет вовсе — их оценки приезжают
 *   внутри чужого ответа;
 * - `IdSource` знает ещё Steam и GOG, но не пишет их сегодня ни один клиент:
 *   чужими идентификаторами приезжают только IMDb и Кинопоиск. У GOG вдобавок
 *   в адресе стоит слаг, а хранится номер каталога — собрать из номера нечего;
 * - у TMDB, Steam и GOG номер бывает у самой карточки, а не среди чужих:
 *   это её собственный источник, и лежит он в `source_id`. Оттуда адрес и
 *   соберётся, когда карточка появится.
 *
 * Имя без адреса остаётся подписью: оно не подсвечивается и не отзывается ни
 * на наведение, ни на щелчок. */
const PAGES = {
  imdb: (value) => `https://www.imdb.com/title/${value}/`,
  kinopoisk: (value) => `https://www.kinopoisk.ru/film/${value}/`,
}

export const stepOfSource = (value, source) => stepOf(value, MAX[source] ?? 10)

// Единица измерения там, где оценка не балл: у Rotten Tomatoes это доля
// положительных рецензий, и без знака она читается баллом, как у соседей.
const UNIT = { rotten: '%' }

/** Оценка так, как она стоит в строке карточки.
 *
 *  У десятибалльной десятая доля показывается всегда, даже нулевая: «IMDb 8»
 *  рядом с «Кинопоиск 8.7» читается как другая шкала, а не как круглая оценка.
 *  У остальных долей нет вовсе — «Rotten Tomatoes 73.0» выдумывает точность,
 *  которой у источника нет. */
export const shownValue = (value, source) =>
  ((MAX[source] ?? 10) === 10
    ? value.toFixed(1)
    : Math.round(value) + (UNIT[source] ?? ''))

/** Незнакомый показывается как есть: пустая подпись хуже неказистой. */
export const nameOf = (source) => NAMES[source] ?? source

/** Источник → адрес, только для тех, у кого он собирается. */
export function pagesOf(externals) {
  const found = new Map()
  for (const { source, value } of externals) {
    if (PAGES[source]) found.set(source, PAGES[source](value))
  }
  return found
}
