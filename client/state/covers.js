/* Адрес обложки у своей ручки. */

/** По номеру карточки — так спрашивают всё, что уже лежит в базе.
 *
 *  Метка момента нужна только перезалившему: адрес ручки от содержимого не
 *  зависит, а отдаёт она сутки кеша — без метки перезалитая обложка осталась бы
 *  прежней до завтра. Кто картинку не менял, метки и не ставит. */
export const byItem = (item_id, stamp = 0) =>
  stamp ? `/poster?item=${item_id}&at=${stamp}` : `/poster?item=${item_id}`

/** По адресу у источника — так спрашивают кандидата, которого в базе ещё нет.
 *  Чужой адрес кодируется целиком: в нём бывают и `?`, и `&`, а подставленный
 *  как есть он стал бы вторым доводом ручки.
 *
 *  Тип едет третьим доводом, и без него не обойтись: обложку чужой формы
 *  бэкенд приводит к нашей, а форма у альбома квадратная. У своей карточки его
 *  спрашивать не надо — там тип лежит в самой строке базы. */
export const bySource = (source, url, kind) =>
  `/poster?source=${source}&url=${encodeURIComponent(url)}&kind=${kind}`

/** Чем показывать обложку строки: своя идёт по номеру, кандидат — через
 *  источник.
 *
 *  Метка приходит доводом, а не берётся у строки, и это не оформление. Строку
 *  раздел перечитывает из базы на каждом заходе, а `CardView` поля под метку не
 *  объявляет вовсе — положенная в строку, она теряется на первом же
 *  перечитывании, адрес выходит прежним, и браузер рисует картинку из суточного
 *  кеша. Ровно так перезалитая руками обложка возвращалась к прежней.
 *
 *  Момент годится любой, лишь бы он двигался при перезаливке: адрес нужен не
 *  точный, а другой. Сборка даёт ему момент последнего сохранения карточки —
 *  заливают обложку только там. */
export const coverFor = (view, stamp) =>
  view.item_id ? byItem(view.item_id, stamp)
    : view.poster_url && bySource(view.source, view.poster_url, view.kind)
