/* Метки карточек, наложенные поверх прочитанного из базы. */

/** Правки набора тегов, ещё не доехавшие до показанных строк.
 *
 *  Перечитывать страницу ленты ради одной метки незачем — следующее чтение
 *  привезёт её из базы, — но до тех пор строка показывала бы устаревшее.
 *  Правок две, и они разного рода: `tagged` заменяет метки одной карточки
 *  целиком, потому что модалка отдаёт то, что теперь на карточке, а не разницу;
 *  `forgotten` вычитается у всех, потому что удалённый из набора тег приехал
 *  вместе с карточками из базы и остался бы висеть меткой. Клик по такой метке
 *  ставит фильтр по номеру, которого больше нет: лента пустеет, а выключить
 *  отбор с экрана нечем.
 *
 *  Общее у двух разделов, а не `$derived` внутри одного: разделов, показывающих
 *  карточки, два — лента и выдача поиска, — и метку ставят из обоих.
 *
 *  Не `marked`: этим именем в том же слое зовётся щелчок по метке, включающий
 *  отбор (`filters.js`), и `session.js` его уже импортирует. */
export function retagged(views, tagged, forgotten) {
  return views.map((view) => {
    const tags = (tagged[view.item_id] ?? view.tags)
      .filter((tag) => !forgotten.includes(tag.id))
    // Нетронутую отдаём той же самой. Строку списка это не бережёт — `{#each}`
    // у ленты ключевой по паре «источник плюс идентификатор», — но новый объект
    // на входе перезапустил бы всё производное внутри карточки, а правка одной
    // метки трогает одну строку из полусотни.
    return tags.length === view.tags.length && !tagged[view.item_id]
      ? view : { ...view, tags }
  })
}
