/* Мерка и арифметика своей полосы прокрутки. */

// Минимальная высота ползунка: на длинном списке доля содержимого делает его
// неухватываемым.
const MIN_THUMB = 28

// Высоты браузер отдаёт целыми, и разница в пиксель бывает округлением, а не
// содержимым.
const NOISE = 1

/** Ползунок для прокручиваемого элемента: коробка и отчёт наблюдателя о её
 *  размере. Какую мерку из отчёта брать, решается здесь — обе известные
 *  поломки полосы были именно на выборе мерки.
 *
 *  Не `clientHeight`: тот целый и округляет вверх, а ползунок, доведённый до
 *  низа, встаёт ровно на высоте области. Округлённая вверх, она выносит его на
 *  полпикселя ниже дорожки — и это переполнение, которое от полосы до `html`
 *  никто не прячет, добавляет странице собственную полосу прокрутки, не
 *  прокручивающую ничего. Замерено на живом окне 04.08.2026: настоящие 1059.6
 *  против 1060 у `clientHeight`.
 *
 *  И не `getBoundingClientRect()`: тот считает превращения предков, а
 *  `scrollHeight` рядом — нет. Пока окно въезжает анимацией `scale(.94)`, эти
 *  двое меряются разными линейками, и ползунок объявляется нужным там, где
 *  прокручивать нечего; остаётся он навсегда, потому что превращение не будит
 *  ни наблюдателя размера, ни прокрутку, а больше переснять мерку некому.
 *  Замерено 24.08.2026: ползунок 263.3 при области 298, то есть 298 × 0.94².
 *
 *  Остаётся `borderBoxSize`: он вёрстанный и дробный разом, и меряет ту же
 *  коробку, что мерил прежний `getBoundingClientRect()` — с полями и рамкой. */
export const thumbFor = (box, sized) =>
  thumbOf(sized.borderBoxSize[0].blockSize, box.scrollHeight, box.scrollTop)

/** Ползунок целиком, либо `null` — прокручивать нечего.
 *
 *  `scale` считается по дорожке самого ползунка, а не долей видимого от всего:
 *  доля верна, только пока высота не подпёрта снизу. Подпёртый ползунок,
 *  доведённый до низа дорожки, при доле не довёл бы список до конца. */
export function thumbOf(visible, total, passed) {
  if (total <= visible + NOISE) return null

  const height = Math.max(MIN_THUMB, visible * (visible / total))
  const room = visible - height
  const range = total - visible
  return { height, offset: room * (passed / range), scale: range / room }
}
