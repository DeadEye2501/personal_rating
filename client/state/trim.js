/* Обрезка текста по границе слова. */

// Знаки, которые на разрыве обещают продолжение в той же строке: «трон, … ещё»
// читается перечислением, которого нет.
const HANGING = /[\s.,:;—–-]+$/

/** Начало текста длиной не больше предела, оборванное по последнему пробелу.
 *
 *  Предел приходит замером — сколько знаков влезло в три строки вместе с
 *  кнопкой, — и приходится он на середину слова чаще, чем на пробел.
 *
 *  Слово без пробелов режется как есть: показать огрызок лучше, чем не
 *  показать ничего. */
export function wordEnd(text, limit) {
  if (limit >= text.length) return text

  const head = text.slice(0, limit)
  // Предел пришёлся на пробел — слово кончилось ровно на нём, и отступать
  // назад значило бы выбросить целое слово, которое влезло.
  const whole = /\s/.test(text[limit])
  // Отрезаем последнее слово вместе с его началом. Границей считается любой
  // пробельный знак, а не только обычный: у TMDB в описаниях попадается
  // неразрывный — замерено, тринадцать штук на девятьсот знаков записанного
  // ответа, — и строку по нему переносят так же.
  const short = head.replace(/\S*$/u, '')
  return (whole || !short ? head : short).replace(HANGING, '')
}
