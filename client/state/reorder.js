/* Куда встаёт строка, которую тащат указателем. */

/** Новый порядок списка после того, как курсор оказался на `y`.
 *
 *  `middles` — середины **всех** строк по порядку, включая перетаскиваемую:
 *  свою она отбрасывает сама. Иначе строка, едущая под курсором, отвечала бы на
 *  вопрос о себе — и каждое движение вниз промахивалось бы на строку. Обе
 *  половины счёта живут здесь по этой же причине: разлучённые, они меряют
 *  разными линейками — одна список со строкой, другая без неё. */
export function dragged(list, from, middles, y) {
  const others = middles.filter((_, at) => at !== from)
  const to = others.findIndex((middle) => y < middle)
  return moved(list, from, to === -1 ? others.length : to)
}

/** Список с переставленной строкой. Новый, а не правленый на месте: порядок
 *  уезжает в базу отдельным вызовом, и при отказе показанное откатывают на
 *  прежний. */
function moved(list, from, to) {
  const next = [...list]
  next.splice(to, 0, ...next.splice(from, 1))
  return next
}
