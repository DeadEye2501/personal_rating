/* Место всплывающей картинки рядом с указателем. */

// Отступ от курсора: вплотную картинка накрывала бы то, на что показывают.
const GAP = 16

/** Справа снизу от указателя, но внутри окна: у нижних строк списка картинка
 *  иначе оказалась бы наполовину за экраном, а у правого края — целиком.
 *  Нижняя граница в ноль на случай окна теснее самой картинки: уведённой в
 *  минус её не видно вовсе. */
export function beside(point, size, view) {
  return {
    left: Math.max(0, Math.min(point.x + GAP, view.width - size.width - GAP)),
    top: Math.max(0, Math.min(point.y + GAP, view.height - size.height - GAP)),
  }
}
