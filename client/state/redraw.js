/* Перезапуск анимации: снять признак, заставить браузер пересчитать стили и
 * вернуть признак обратно.
 *
 * Пересчёт посреди — не украшение, а весь смысл. Браузер сличает состояние на
 * конец задачи, и снятый в той же задаче класс для него не снимался вовсе.
 * Отложить возврат кадром не помогает: колбэк `requestAnimationFrame`
 * выполняется **до** пересчёта стилей того же кадра. Чтение `offsetWidth`
 * пересчёт вызывает принудительно — приём, которым это сделано и в макете.
 *
 * Вынесено сразу, потому что второй потребитель известен и близок: тем же
 * приёмом отрастает гистограмма в плане 8.
 *
 * Это способ для узла, который обязан пережить перезапуск, — кнопки, столбика.
 * Там, где узел можно пересоздать целиком, анимация заводится сама, и
 * пересоздание дешевле: так сделан переход между разделами. */
export function redrawn(element, name) {
  element.classList.remove(name)
  void element.offsetWidth
  element.classList.add(name)
}
