/* Перезапуск анимации на узле, который обязан его пережить. */

/* Пересчёт стилей посреди — не украшение, а весь смысл. Браузер сличает
 * состояние на конец задачи, и снятый в той же задаче класс для него не
 * снимался вовсе. Отложить возврат кадром не помогает: колбэк
 * `requestAnimationFrame` выполняется **до** пересчёта стилей того же кадра.
 * Чтение `offsetWidth` вызывает пересчёт принудительно — приём, которым это
 * сделано и в макете.
 *
 * Способ этот для узла, который пересоздавать нельзя: кнопки, столбика. Там,
 * где узел можно пересоздать целиком, анимация заводится сама и обходится
 * дешевле — так сделан переход между разделами.
 *
 * Вынесено сразу, потому что второй потребитель известен и близок: тем же
 * приёмом отрастает гистограмма в плане 8. */
export function redrawn(element, name) {
  element.classList.remove(name)
  void element.offsetWidth
  element.classList.add(name)
}
