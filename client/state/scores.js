/* Нотация оценки: ярлык словом, ступень шкалы, среднее, доля звезды. */

// Цвета лежат в палитре (--score-1…10), ярлыки — здесь. Значения из макета.
export const LABELS = {
  10: 'Шедевр', 9: 'Отлично', 8: 'Хорошо', 7: 'Интересно', 6: 'Неплохо',
  5: 'Средне', 4: 'Посредственно', 3: 'Уныло', 2: 'Плохо', 1: 'Отвратительно',
}

// Три стороны, по которым оценивают игру. Ключи — поля `Rating` в базе и
// доводы моста; подписи — из макета.
export const ASPECTS = [
  { key: 'visual', label: 'Визуал' },
  { key: 'narrative', label: 'Нарратив' },
  { key: 'gameplay', label: 'Геймплей' },
]

const STEPS = 10

/** Ступени шкалы по порядку. Ряд звёзд, строка фильтра и столбец
 *  гистограммы перебирают одно и то же, и объявлено оно один раз: длина
 *  шкалы уже сказана в `STEPS`. */
export const SCALE = Array.from({ length: STEPS }, (_, at) => at + 1)

/** Любая шкала приводится к десятибалльной: цвет агрегатора берётся из той же
 *  нотации, что и своя оценка.
 *
 *  Округление к ближайшему, а не вверх: доля 0.92 у GOG — это девятая ступень,
 *  а не десятая, и так сказано в плане прямо. Вверх сдвинуло бы вверх всю
 *  чужую шкалу — десятая доставалась бы всему выше 90 %, тогда как своя
 *  десятка это ровно десять.
 *
 *  Зажим обязателен: чужой ответ бывает и нулём, и больше максимума, а
 *  `--score-0` это отсутствие цвета и невидимая цифра. */
export function stepOf(value, max) {
  return Math.min(STEPS, Math.max(1, Math.round((value / max) * STEPS)))
}

export const colorOf = (step) => `var(--score-${step})`

/** Дробные оценки округляются вниз — правило общее для всего показа. */
export function verdictOf(score) {
  return LABELS[Math.floor(score ?? 0)] ?? ''
}

/** Среднее по выставленным шкалам, а не по трём всегда: у игры может быть
 *  заполнена одна, и деление на три занизило бы втрое.
 *
 *  Пустое отбирается по тождеству, а не по истинности: ноль — законная
 *  оценка, и отброшенный вместе с пустотой он поднял бы среднее. */
export function average(values) {
  const given = values.filter((value) => value !== null && value !== undefined)
  if (!given.length) return null
  return given.reduce((sum, value) => sum + value, 0) / given.length
}

/** Оценка карточки одним числом: у игры среднее выставленных сторон, у кино
 *  своя оценка как есть. Считается здесь, а не берётся из ответа базы, ради
 *  промежутка: пока человек проставляет три стороны игры, ответа ещё нет, а
 *  число под ними меняться обязано. */
export function meanOf(rating, kind) {
  if (kind !== 'game') return rating?.score ?? null
  return average(ASPECTS.map((one) => rating?.[one.key] ?? null))
}

/** Цвет, которым пишется своя оценка: ступень по целой части. Снятая оценка
 *  красится первой ступенью — ярлыка у неё всё равно нет, а цвет нужен, иначе
 *  переменная останется неопределённой и текст пропадёт. */
export const toneOf = (score) => colorOf(Math.max(1, Math.floor(score ?? 1)))

/** Остаток для дробной звезды: закрашенная часть лежит поверх контурной и
 *  обрезается по ширине. */
export const partOf = (score) => score - Math.floor(score)
