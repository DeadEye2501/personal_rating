/* Порядок операций по одной строке выдачи. */

import { keyOf } from './reread.js'

/** Строка выдачи живёт своей жизнью: её заводят по показу и по нажатию звезды
 *  разом, а оценку ставят тремя шкалами подряд. Без порядка это две беды.
 *
 *  Заведение — **одно на строку**: два `ensure` подряд дают два ответа, и
 *  второй возвращает строку такой, какой она была до первого.
 *
 *  Записи идут **по очереди**: у игры три шкалы уезжают одним вызовом, и
 *  вторая, пущенная вперегонки с первой, считает от того же пустого состояния
 *  и затирает её.
 *
 *  Своей памятью на каждую выдачу, а не общей на модуль: смена запроса приносит
 *  другие строки, и начатое по старым их не касается. */
export function rowTurns() {
  const started = new Map()
  const queues = new Map()

  /** Кладёт в память само возвращаемое обещание — вместе с забвением внутри.
   *  Дождавшийся просит следующим действием, и память обязана освободиться
   *  раньше, чем он это сделает: положи туда обещание без забвения, и строка,
   *  которую уже завели, второго жеста не дождётся — ей вернут ответ, готовый
   *  минуту назад.
   *
   *  Забывается и доведённое, и сорвавшееся: память держит начатое, иначе
   *  строка, заведение которой не удалось, второго шанса не получит. */
  function remember(kept, key, going) {
    let stored
    stored = going.finally(() => {
      if (kept.get(key) === stored) kept.delete(key)
    })
    kept.set(key, stored)
    return stored
  }

  function once(view, run) {
    const key = keyOf(view)
    if (!started.has(key)) {
      remember(started, key, Promise.resolve().then(run))
    }
    return started.get(key)
  }

  function inTurn(view, run) {
    const key = keyOf(view)
    // Сорвавшаяся запись очередь не запирает: следующая идёт в любом случае, а
    // отказ достаётся тому, кто её просил.
    const after = (queues.get(key) ?? Promise.resolve()).catch(() => {})
    return remember(queues, key, after.then(run))
  }

  return { once, inTurn }
}
