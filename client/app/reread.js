/* Что раздел делает со своим списком, когда карточку записали или удалили. */

import { numbered } from '$api/bridge.js'
import { textChannel } from './visible.js'

/** Чем строка выдачи отличается от соседки. Номера у неё может не быть вовсе —
 *  до того, как круг загрузки доехал, — а пара «источник плюс идентификатор»
 *  есть всегда, и по ней же её узнаёт мостовая память.
 *
 *  Половиной ключа нельзя: `157336` есть и у TMDB, и у Steam, и это разные
 *  вещи. */
export const keyOf = (view) => `${view.source}:${view.source_id}`

export const same = (each, view) => keyOf(each) === keyOf(view)

/** Удалённую карточку раздел убирает у себя: перечитывать ленту ради одной
 *  пропавшей значило бы потерять место, на котором человек стоял. */
export const without = (views, gone) =>
  views.filter((each) => gone.item_id != null
    ? each.item_id !== gone.item_id
    : !same(each, gone))

/** Приехавшая из базы строка без пустого синопсиса: лента его не возит вовсе
 *  (см. `view_from_item` в питоне), и положенное доливом пустое поле стёрло бы
 *  показанный текст — у кандидата выдачи он от источника, у своей карточки от
 *  второго круга. */
export const withoutText = ({ synopsis, ...row }) => row

/** Слова отказа перечитывания. Одной строкой на оба раздела: они и так
 *  зовут его одинаково, а разойдясь, сказали бы человеку об одной беде
 *  по-разному. */
export const NOT_REREAD = 'Не удалось перечитать карточку'

/** Перечитать записанную карточку, если она ещё в списке.
 *
 *  Одним объявлением на оба раздела: ленте и выдаче поиска перечитывать нужно
 *  одинаково, и разошлись бы они молча — свидетеля у такого расхождения нет.
 *  Записанной заново в списке может не быть: раздел мог смениться, пока запись
 *  доезжала до базы, — тогда перечитывать нечего, строка придёт со следующей
 *  порцией.
 *
 *  Отказ отдаётся зовущему, а не глотается: у каждого раздела свой журнал и
 *  своя плашка, а слова у отказа общие — `NOT_REREAD`.
 *
 *  Кладёт приехавшее не сама: у ленты строка ищется по номеру, у выдачи поиска —
 *  по паре «источник плюс идентификатор», потому что там она могла быть
 *  кандидатом без номера вовсе. */
export function again(views, done, ops, put) {
  if (!views.some((each) => each.item_id === done.item_id)) return null
  return refreshed(done, ops, put)
}

/** Сам поход за строкой и её текстом. Наружу не отдаётся: единственная дверь
 *  сюда — `again`, и она же сторожит, что строка ещё на экране. Открой её, и
 *  сторожа можно было бы обойти, не заметив. */
function refreshed({ item_id }, ops, put) {
  // Синопсис приезжает вторым вызовом, потому что лента его не возит вовсе
  // (см. `view_from_item` в питоне). Без него перечитанная строка легла бы
  // поверх показанной с пустым текстом — правь карточку, и синопсис пропадал бы
  // с экрана до перезахода в раздел.
  //
  // Канал у текста общий со вторым кругом (`visible.js`), и собирает его
  // `textChannel` — одним объявлением на обе двери. От соседнего вызова строки
  // он при этом отдельный: на общем канале второй вызов отменял бы первый.
  return Promise.all([
    numbered('feed.views_of', [item_id], { channel: 'views', ops }),
    // Отказ чтения текста перечитывания не отменяет: строка правленой карточки
    // важнее её синопсиса. Не приехал текст — строка остаётся с показанным.
    numbered('feed.synopsis', item_id, { channel: textChannel(item_id), ops })
      .catch(() => ''),
  ]).then(([[fresh], synopsis]) => {
    if (!fresh) return
    const row = withoutText(fresh)
    put(synopsis ? { ...row, synopsis } : row)
  })
}
