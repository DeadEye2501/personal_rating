/* Единственный способ поступить с отказом операции. */

/** Молчаливый отказ не оставляет следа нигде: отменённое и устаревшее — это
 *  уход со страницы и вытеснение канала, штатный ход, о котором нечего сказать
 *  ни человеку, ни журналу.
 *
 *  Всё остальное записывается всегда, а плашкой показывается не всегда:
 *  сорвавшемуся агрегатору на карточке отведено пустое место, и плашка про него
 *  была бы шумом. Поэтому `say` необязателен, а запись — нет: ни один вызов
 *  моста не остаётся без следа. */
export function reported(error, where, say = null) {
  if (error.silent) return
  console.warn(where, error)
  say?.()
}

/** Место у каждого своё, а связка одна: «записать под своим именем и сказать
 *  человеку своими словами». Семь копий отличались ровно словом места.
 *
 *  Запасные слова нужны там, где отказ ловят одним обработчиком на несколько
 *  разных вызовов: сказать что-то надо и про тот, у которого своих слов нет. */
export const complaining = (where, say, spare = 'Не удалось выполнить операцию') =>
  (error, text = spare) => reported(error, where, () => say(text))
