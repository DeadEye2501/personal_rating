/* Что делать с карточкой, попавшей в поле зрения. */

/* Обложку берёт сам браузер — она едет ручкой, а не мостом. Здесь остаются два
 * обращения, и оба только для того, что уже в базе: у кандидата поиска нет
 * `imdb_id`, и спросить агрегаторов о нём нечем. */

import { numbered } from '$api/bridge.js'

// Через сколько дней карточка считается просроченной. Число из правила
// перезапроса по сроку: обновляются только сезоны, серии и оценки.
const FRESH_DAYS = 30
const DAY = 24 * 60 * 60 * 1000

// Кого уже спрашивали. Память живёт здесь, а не в ленте, потому что это
// политика квот, а не показ: прокрутка вверх-вниз иначе гоняла бы круги
// загрузки по кругу. И переживает она смену раздела нарочно — карточка та же,
// и спрашивать о ней второй раз незачем.
const asked = new Set()

/** Возвращает приехавшие оценки агрегаторов или `null`, если спрашивать было
 *  нечего. Возврат обязателен: без него приехавшее некуда положить, и кружок
 *  на месте оценки крутился бы до перезахода в раздел, хотя оценки уже в базе. */
export async function onCardShown(view, ops) {
  if (!view.item_id || asked.has(view.item_id)) return null
  asked.add(view.item_id)

  // Канал у каждой карточки свой, а не общий по имени вызова. Общий значил бы,
  // что десяток видимых карточек гасят друг друга: выжила бы последняя, а
  // остальные ушли бы родом `stale`, который молчит — и настоящий отказ
  // источника не попал бы даже в лог.
  //
  // Номера ложатся в `ops`: человек ушёл с раздела — начатое гасится, и квота
  // агрегаторов не тратится на ответ, которого никто не ждёт.
  const channel = `card:${view.item_id}`
  if (stale(view)) {
    await quietly('world.refresh_series', view.item_id, { channel, ops })
  }
  return quietly('world.enrich', view.item_id, view.kind, { channel, ops })
}

/** Просрочку считает и бэкенд — `SeriesRefresh` тихо ничего не делает в трёх
 *  случаях. Второй раз она считается здесь не по забывчивости: вызов, который в
 *  подавляющем большинстве случаев не сделает ничего, стоит потока на стороне
 *  питона и пересечения границы на каждой карточке прокрутки. */
export function stale(view) {
  if (view.kind !== 'series' || view.source !== 'tmdb') return false
  if (!view.synced_at) return false
  return Date.now() - Date.parse(view.synced_at) > FRESH_DAYS * DAY
}

async function quietly(path, ...args) {
  // Отказ агрегатора ничему не мешает и ничего не сообщает: на месте оценки
  // просто ничего, без следа и без плашки. Но и молча не глотаем: в лог.
  try {
    return await numbered(path, ...args)
  } catch (error) {
    if (!error.silent) console.warn(path, error)
    return null
  }
}
