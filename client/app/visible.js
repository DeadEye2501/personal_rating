/* Что делать с карточкой, попавшей в поле зрения. */

/* Обложку берёт сам браузер — она едет ручкой, а не мостом. Здесь остаются три
 * обращения, и все три только для того, что уже в базе: у кандидата поиска нет
 * ни номера строки, ни `imdb_id` — ни синопсиса спросить, ни агрегаторов. */

import { numbered, textChannel } from '$api/bridge.js'
import { reported } from './trouble.js'

// Через сколько дней карточка считается просроченной. Число из правила
// перезапроса по сроку: обновляются только сезоны, серии и оценки.
const FRESH_DAYS = 30
const DAY = 24 * 60 * 60 * 1000

// Кого уже спрашивали об оценках. Память живёт здесь, а не в ленте, потому что
// это политика квот, а не показ: прокрутка вверх-вниз иначе гоняла бы круги
// загрузки по кругу. И переживает она смену раздела нарочно — карточка та же,
// и спрашивать о ней второй раз незачем.
//
// Синопсис ею не закрыт, и это не забывчивость: см. `onCardShown`.
const asked = new Set()

/** Номер карточки SQLite выдаёт повторно — `item` заведён без `AUTOINCREMENT`.
 *  Не забыв удалённую, память приняла бы заведённую заново за уже спрошенную:
 *  оценок за неё не спросил бы никто, и кольца на их месте крутились бы до
 *  конца сеанса. */
export const forgetCard = (item_id) => asked.delete(item_id)

/** Что доехало о карточке, пока она на экране, кладётся правкой — **каждое, как
 *  только приехало**, а не одним снимком в конце. Кладёт его `put`, а не возврат
 *  функции: две половины круга приезжают врозь, синопсис за миллисекунды с
 *  диска, оценки — до двадцати секунд из сети. Снимок, собранный до сети,
 *  затирал бы всё, что случилось со строкой за эти секунды: человек правит
 *  синопсис, `refreshed` кладёт новый текст, а вернувшийся круг кладёт прежний.
 *
 *  Пустое в правку не кладётся — молчание не должно стирать показанное;
 *  `enriched` ставится всегда, и он гасит кружки у тех, за кого спрашивать было
 *  нечем или некому.
 *
 *  **Синопсис спрашивается на каждый показ, а оценки — раз за сеанс.** Разница
 *  не в аккуратности, а в том, что с текстом происходит: смена вкладки,
 *  раздела, фильтра или сортировки перечитывает ленту, и строки в ней — свежие
 *  из базы, без синопсиса. Под общей памятью текст был бы одноразовым: пропал
 *  бы на первом же переключении и не вернулся никогда, потому что спрашивать
 *  «второй раз» память запрещает. Проверено живьём 23.08.2026 — так оно и
 *  повело себя. Цена повтора — чтение одной строки базы по номеру: ни сети, ни
 *  квот, ни второго файла базы. */
export async function onCardShown(view, ops, put) {
  if (!view.item_id) {
    put({ enriched: true })
    return
  }

  // Канал у каждой карточки свой, а не общий по имени вызова. Общий значил бы,
  // что десяток видимых карточек гасят друг друга: выжила бы последняя, а
  // остальные ушли бы родом `stale`, который молчит — и настоящий отказ
  // источника не попал бы даже в лог.
  //
  // Номера ложатся в `ops`: человек ушёл с раздела — начатое гасится, и квота
  // агрегаторов не тратится на ответ, которого никто не ждёт.
  const channel = `card:${view.item_id}`

  // Имя канала текста собирает `textChannel`: за синопсисом ходят двое — этот
  // круг и перечитывание правленой карточки, — и канал у них общий нарочно,
  // чтобы свежий текст гасил приехавший позже прежний. От канала самой карточки
  // он при этом отдельный: иначе чтение текста гасило бы оценки агрегаторов.
  //
  // В отменяемые номер текста не кладётся, и это не забывчивость: спрашивают
  // его на каждое появление карточки, то есть на прокрутку вверх-вниз сотнями,
  // а гасить нечего — чтение одной строки кончается за миллисекунды и ни квоты,
  // ни сети не стоит. Копился бы список, который целиком уезжает в `cancel`.
  const text = quietly('feed.synopsis', view.item_id,
                       { channel: textChannel(view.item_id) })
    .then((synopsis) => { if (synopsis) put({ synopsis }) })

  const external = await rated(view, channel, ops)
  put(external ? { external, enriched: true } : { enriched: true })
  await text
}

/** Оценки агрегаторов — раз за сеанс на карточку. `null`, если о ней уже
 *  спрашивали: класть в правку нечего, а прежние оценки уже показаны. */
async function rated(view, channel, ops) {
  if (asked.has(view.item_id)) return null
  asked.add(view.item_id)

  if (stale(view)) {
    await quietly('world.refresh_series', view.item_id, { channel, ops })
  }
  return quietly('world.enrich', view.item_id, view.kind, { channel, ops })
}

/** Просрочку считает и бэкенд — `SeriesRefresh` тихо ничего не делает в трёх
 *  случаях. Второй раз она считается здесь не по забывчивости: вызов, который в
 *  подавляющем большинстве случаев не сделает ничего, стоит потока на стороне
 *  питона и пересечения границы на каждой карточке прокрутки. */
export function stale(view) {
  if (view.kind !== 'series' || view.source !== 'tmdb') return false
  if (!view.synced_at) return false
  return Date.now() - Date.parse(view.synced_at) > FRESH_DAYS * DAY
}

async function quietly(path, ...args) {
  // Отказ агрегатора ничему не мешает и ничего не сообщает: на месте оценки
  // просто ничего, без следа и без плашки. Но и молча не глотаем: в лог.
  try {
    return await numbered(path, ...args)
  } catch (error) {
    reported(error, path)
    return null
  }
}
