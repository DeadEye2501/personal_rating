<!-- Раздел «Поиск»: сначала своя выдача, потом внешняя. Спрашивают её двумя
     жестами — строкой в шапке и кликом по имени в карточке, — и показывает она
     их одинаково. -->
<script>
  import { untrack } from 'svelte'

  import Feed from '$components/Feed.svelte'
  import Gone from '$components/Gone.svelte'
  import { call, cancel, drop, lastOp, numbered } from '$api/bridge.js'
  import { owned } from '$api/owned.svelte.js'
  import { passes } from '$state/filters.js'
  import { retagged } from '$state/marking.js'
  import { flipped, swept } from '$state/session.js'
  import { rowTurns } from './inturn.js'
  import { keyOf, refreshed, same, without, withoutText } from './reread.js'
  import { aspected, scored, wished } from './marks.js'
  import { complaining, reported } from './trouble.js'
  import { onCardShown } from './visible.js'

  let { session, query = null, person = null, expected = [], root = null,
        tagged = {}, forgotten = [], saved = null, removed = null,
        reviewed = null, ontrouble, onmark, onperson, onopen, onedit, ondelete,
        onreview, ontag } = $props()

  let views = $state([])
  // Список убранного вместо выдачи. Признак приходит из ответа, а не
  // выводится из строки поиска: «`deleted` означает показать убранное» —
  // логика, и решает её бэкенд.
  let gone = $state(false)
  // Догружать нечего, пока первая порция чужой выдачи не приехала: до неё у
  // ленты либо пусто, либо своя половина, а смещение у моста ещё нулевое.
  let ready = $state(false)
  let done = $state(false)
  const ops = owned()

  // Тип содержимого отдельной величиной, а не чтением `session` в эффекте:
  // прочитанный там, он пометил бы эффект грязным на любую пересборку сеанса —
  // и клик по жанру на карточке перезапускал бы весь поиск, включая поход в
  // сеть. А метка объявлена мгновенным фильтром, который работает офлайн.
  const kind = $derived(session.kind)

  // Фильтры работают и в поиске. Спросить источник с фильтром нечем — у TMDB и
  // магазинов нет ни наших тегов, ни наших оценок, — поэтому ответ приходит
  // целиком, а отсев идёт здесь, тем же правилом, что и в ленте.
  //
  // Правки набора тегов накладываются до отсева: отбор идёт по меткам, и
  // фильтровать надо по тем, что человек видит, а не по приехавшим из базы.
  const cards = $derived(retagged(views, tagged, forgotten)
    .filter((view) => passes(view, session.filters)))

  // Ни один вызов моста не остаётся без обработчика: невыполненное обещание в
  // JS не даёт ни плашки, ни записи — то есть ровно то молчание, которое
  // правило отказов запрещает.
  const lost = complaining('поиск', ontrouble)

  // Жест ровно один за раз: строка снимает человека, клик по имени снимает
  // строку — оба снятия делает сборка, здесь остаётся выбор ветки. Ранняя
  // ветка и есть то, что делает жест единственным: при непустом человеке
  // строка не читается вовсе.
  $effect(() => {
    const clicked = person
    // Начатое по прежней выдаче новой не касается: её строки мост помнит под
    // старым номером, и обещание, отданное новому жесту, отвергнется
    // «устаревшим» — молча.
    turns = rowTurns()
    if (clicked) { about(clicked, kind).catch(lost); return }
    if (!query?.text) { forget(); return }
    look(query.text, kind).catch(lost)
  })

  /** Спрашивать нечего — но начатое прежде обязано перестать доезжать.
   *
   *  Устаревшее отбрасывается сравнением с номером канала, а тот меняется
   *  только при новом вызове: сними строку без него, и ответ прежней операции
   *  доедет своевременным. Так игровая выдача ложилась во вкладку сериалов
   *  через двадцать секунд после того, как её очистили. */
  function forget() {
    drop('search')
    cancel(ops)
    views = []
    gone = false
    ready = false
    done = false
  }

  /** Выдача по клику на имя приезжает собранной: своя половина и чужая сложены
   *  на стороне бэкенда, и второго шага у этого жеста нет.
   *
   *  Лента гасится до запроса, а не после: своей половины, которая у строки
   *  приезжает мгновенно, здесь нет, и до двадцати секунд ожидания под пустым
   *  полем поиска висела бы выдача прошлого жеста.
   *
   *  Канал тот же, что у строки: новый жест обязан отменять предыдущий, а
   *  разные каналы оставили бы обе выдачи в гонке. */
  async function about({ domain, entity_id }, forKind) {
    views = []
    gone = false
    // Второго шага у этого жеста нет вовсе — обе половины приезжают
    // собранными, — и просить ещё у моста нечего: своей памяти запроса он под
    // клик не заводит.
    ready = false
    done = true
    const found = await numbered('search.by_person', domain, entity_id, forKind,
                                 { channel: 'search', ops })
    arrived(found)
    refused(found)
  }

  /** Очередная порция чужой выдачи: приезжает и первая, и все следующие.
   *
   *  Смещение помнит мост, поэтому обе просят одинаково — и номер операции у
   *  них тоже общий: мостовая память узнаёт выдачу по нему, а с новым номером
   *  сюда всегда приходило бы «устарело».
   *
   *  Конец называет источник, а не длина списка: из двадцати строк отсев
   *  нерелевантного и снятие убранного оставляют меньше, и считать по
   *  показанному значило бы вставать на первой же убранной строке. */
  async function portion(silent = false) {
    const next = await numbered('search.external',
                                { channel: 'search', op: lastOp('search') })
    done = !next.more
    arrived(next)
    refused(next, silent)
  }

  /** Отвечает ленте, есть ли смысл просить ещё.
   *
   *  Тёзка из `LibraryScreen` повтором не является, и общего модуля догрузки
   *  план не заводит нарочно: у библиотеки смещение считает страница
   *  (`views.length`), а конец выводится из длины порции; здесь смещение помнит
   *  мост, а конец называет источник — из двадцати строк отсев оставляет
   *  меньше, и длина не значит ничего. Общая у двух разделов только оболочка
   *  «занято — не проси», а её вынос связал бы разделы ради четырёх строк. */
  async function more() {
    if (done || !ready) return false
    try {
      await portion(true)
      return !done
    } catch (error) {
      // Молча, но со следом в журнале: плашка в проекте — про жест человека, а
      // эту порцию просил не он, а лента. У Google Books `503` — обычная икота:
      // замерено 23.08.2026, восемь запросов выдачи из десяти, и повтор вытянул
      // не все. Красная надпись на прокрутке говорила бы «сломалось» там, где
      // источник просто икнул; виток останавливается, а следующая прокрутка
      // просит снова — метка дна опять попадает в поле зрения.
      reported(error, 'search.external')
      return false
    }
  }

  async function look(text, forKind) {
    // Признаки гасятся до запроса, а не по приезде ответа.
    //
    // `gone` — потому что своя половина приходит за миллисекунды, а чужая идёт
    // в сеть до двадцати секунд, и всё это время найденное рисовалось бы
    // строками списка убранного, с кнопкой возврата вместо оценки.
    //
    // `ready` и `done` — потому что прежняя выдача уже дала право просить ещё.
    // Человек дописал строку, лента укоротилась, метка дна показалась — и
    // догрузка ушла бы **тем же номером операции**, что и первая порция новой
    // строки. Мост двигает смещение до ответа, а складывает после: оба ответа
    // читают один снимок показанного, и последний затирает первого. На экране
    // обе порции, в памяти одна — и строки потерянной не заводятся вовсе,
    // `ensure` отвечает «устарело», а «устарело» молчит.
    gone = false
    ready = false
    done = false

    // Своё показывается сразу: локальная база отвечает за миллисекунды.
    views = await numbered('search.local', forKind, text,
                           { channel: 'search', ops })

    // Внешнее доливается по готовности и складывается со своим на стороне
    // моста: `merge_results` живёт в модели ровно потому, что складывать
    // приходится клиенту, и второго его объявления быть не должно.
    try {
      await portion()
      // Признак ставится после первой порции, а не до запроса: до её приезда
      // смещение у моста ещё нулевое, и прокрутка успела бы попросить вторую
      // порцию первой.
      ready = true
    } catch (error) {
      lost(error, 'Внешняя база недоступна')
      // Право просить ещё даётся и после сорвавшейся порции — но только своей.
      // Смещение у моста не сдвинулось, повторить её можно, а просить больше
      // некому: `more()` стоит на этом признаке, и догрузка молчала бы до конца
      // строки запроса. Случай не редкий: у Google Books `503` — обычная икота,
      // замер назван в `more()`.
      //
      // Молчаливый отказ сюда не входит, и это не мелочь: `stale` означает
      // «эту выдачу спрашивает уже другая строка», и признак встал бы поверх
      // нуля, поставленного ею. Новая строка своей первой порции ещё не
      // получила, а прокрутка уже просила бы вторую — тем же номером операции,
      // то есть ровно та гонка двух порций, которую проект чинил в книгах.
      if (!error.silent) ready = true
    }
  }

  /** Отказ источника — поле в ответе, а не исключение. Пустая выдача при этом
   *  молчит: пустая лента и есть ответ.
   *
   *  Приехавшее **дописывается**, а не заменяет собой список: мост помнит
   *  показанное и отдаёт хвост — своей половины и уже показанных чужих строк в
   *  нём нет. Замени им список, и первая порция стёрла бы свою выдачу, а
   *  вторая — первую.
   *
   *  Клик по имени приходит сюда же и приезжает целиком, но список перед ним
   *  гасится, так что дописывание и там кладёт ровно приехавшее. */
  function arrived(answer) {
    gone = answer.removed
    views = [...views, ...answer.views]
  }

  /** Отказ источника в приехавшем ответе.
   *
   *  Плашка бывает при двух условиях сразу: спрашивал человек, а не лента, и
   *  ответ не принёс **ни одной новой** строки. Новой, а не вообще: мост помнит
   *  показанное и отдаёт хвост, так что книга, уже лежащая в библиотеке,
   *  приезжает в приращении пустотой. Плашка при полном экране от этого
   *  возможна — отказ-то настоящий, — но случай узкий: чужая половина обязана
   *  совпасть со своей целиком.
   *
   *  Оба условия из живого окна 23.08.2026. Половин у выдачи две — каталог и
   *  книги автора, — и отказ одной при полной второй означает не «база
   *  недоступна», а «часть ответа не доехала»: строки на экране, а плашка
   *  говорит «сломалось». У Google Books `503` при этом обычная икота: восемь
   *  запросов выдачи из десяти в том замере, и повтор вытянул не все.
   *
   *  Молчание не безнаказанное: пустая выдача с отказом плашку получает, и
   *  человек узнаёт, что искать было некому. */
  function refused(answer, silent = false) {
    if (!answer.refusals.length) return
    if (silent || answer.views.length) reported({ kind: 'refusal' }, 'search.external')
    else ontrouble('Внешняя база недоступна')
  }

  /** Снять пометку об удалении. Карточка не возвращается — её нет; игра
   *  просто снова находится поиском.
   *
   *  Строка убирается со списка сразу, не дожидаясь перезапроса: спрашивать
   *  бэкенд заново незачем, а видеть её на месте после нажатия человек не
   *  должен. */
  async function restore(view) {
    await call('library.restore', view.kind, view.source, view.source_id)
    views = views.filter((each) => !same(each, view))
  }

  /** Кандидат становится карточкой: детальный ответ источника и обложка, запись
   *  в базу целиком, перечитывание строки. Отдаёт свежую карточку либо род
   *  отказа — говорить о нём или молчать, решает тот, кто позвал.
   *
   *  Предупреждения о совпадении названия здесь пока нет. Окно для него уже
   *  есть — `components/Confirm.svelte`, план 8, — не хватает самой проверки на
   *  совпадение; спека требует её именно тут: у игр два магазина, и одна игра
   *  лежит в обоих двумя кандидатами. */
  async function adopt(view) {
    // Тот же номер: кандидата мост берёт из выдачи, которую помнит под ним.
    const outcome = await numbered('search.ensure', view.source, view.source_id,
                                   { channel: 'search', op: lastOp('search') })
    if (outcome.outcome !== 'found') return { refused: outcome.outcome }

    // Перечитываем одну строку: у кандидата не было ни жанров словами, ни
    // состава, ни длительности.
    // Канал на строку, а не общий: у двадцати одновременных догрузок общий
    // пропустил бы только последний ответ, а остальные ушли бы «устаревшими» —
    // молча, и строка осталась бы кандидатом навсегда.
    const [fresh] = await numbered('feed.views_of', [outcome.value],
                                   { channel: `views:${keyOf(view)}`, ops })
    if (fresh) patch(fresh, withoutText(fresh))
    return { fresh }
  }

  const REFUSED = {
    refusal: 'Внешняя база недоступна',
    missing: 'Источник больше не знает такой карточки',
  }

  /** Жест человека: отказ говорится плашкой. Показ карточки — не жест, и там
   *  отказ молчит; см. `shown`. */
  async function asked(view) {
    const { fresh, refused } = await adopting(view)
    if (refused) ontrouble(REFUSED[refused])
    return fresh ?? null
  }

  // Порядок операций по строке: заведение одно на всех, записи идут по
  // очереди. Своя память на каждую выдачу — смена запроса приносит другие
  // строки, и начатое по старым их не касается.
  let turns = rowTurns()

  const adopting = (view) => turns.once(view, () => adopt(view))

  /** Долив полей, а не замена строки целиком. Ответы кругов и нажатие человека
   *  идут вперегонки, и снимок строки, взятый до `await`, затирает то, что
   *  случилось после него: так пропадала поставленная оценка — в базе она
   *  оставалась, а с экрана исчезала ровно в тот миг, когда доезжали оценки
   *  агрегаторов.
   *
   *  Заведённая карточка кладётся тем же доливом: она правда обо всём, что
   *  лежит в базе, но не о свёрнутости — та живёт только на странице, и заменой
   *  целиком свёрнутая строка разворачивалась бы сама, едва догрузившись. */
  function patch(view, fields) {
    views = views.map((each) => same(each, view) ? { ...each, ...fields } : each)
  }

  /** Все три эффекта ниже слушают **только** свой сигнал: `views` они и читают,
   *  и пишут, а такой круг проект уже ловил — эффект по своему же списку не
   *  кончается никогда.
   *
   *  Правленую карточку выдача перечитывает у себя, а не спрашивает источник
   *  заново: это поход в сеть ради того, что уже лежит в базе. */
  $effect(() => {
    const done = saved
    if (done) untrack(() => again(done))
  })

  $effect(() => {
    const gone = removed
    if (gone) untrack(() => { views = without(views, gone) })
  })

  // Записанная рецензия правит свою строку на месте, как и в ленте: текст уже
  // здесь, и перечитывать ради него карточку из базы незачем.
  $effect(() => {
    const written = reviewed
    if (written) untrack(() => patch(written.view, written.fields))
  })

  function again(done) {
    if (!views.some((each) => each.item_id === done.item_id)) return

    refreshed(done, ops, (fresh) => patch(fresh, fresh))
      .catch((error) => lost(error, 'Не удалось перечитать карточку'))
  }

  /** Показанная строка догружается целиком: сначала карточка от источника и
   *  запись в базу, потом оценки агрегаторов. Их спрашивают по `imdb_id`, а он
   *  приезжает только с детальным ответом, — раньше круга 2 круг 3 не начать.
   *
   *  Отказ здесь молчит: двадцать плашек на одну прокрутку — шум, из которого
   *  не видно ни одной настоящей беды. В журнал он идёт всё равно, потому что
   *  ни один вызов моста не остаётся без следа. */
  async function shown(view) {
    const full = view.item_id ? view : await loaded(view)
    if (!full) return

    await onCardShown(full, ops, (fields) => patch(full, fields))
  }

  async function loaded(view) {
    const { fresh, refused } = await adopting(view)
    if (refused) reported({ kind: refused }, 'догрузка кандидата')
    return fresh ?? null
  }

  /** Отметка ставится по карточке — оценка, шкала, закладка, — а карточки у
   *  кандидата ещё нет: сначала заводим, потом отмечаем. Второе нажатие по той
   *  же строке заведения уже не требует — у неё есть номер.
   *
   *  Записи по строке идут по очереди, и каждая берёт строку заново: у игры три
   *  шкалы уезжают одним вызовом, и вторая, посчитанная от снимка, взятого до
   *  `await`, затирает первую — в базе остаётся последняя. */
  const applying = (view, put) => turns.inTurn(view, async () => {
    const full = view.item_id ? view : await asked(view)
    if (!full) return

    const now = views.find((each) => same(each, full)) ?? full
    patch(now, await put(now))
  })

  // Ждать заведения свёрнутости незачем: это показ, а не запись.
  const collapse = (view) => patch(view, flipped(view, session.collapsed))

  // Нажали тумблер — он забирает власть у тронутых шевроном строк. Величина
  // отдельная по той же причине, что и `kind`: прочитанная в эффекте, она
  // метила бы его грязным на любую пересборку сеанса.
  const all = $derived(session.collapsed)

  $effect(() => {
    const pressed = all
    untrack(() => { views = swept(views, pressed) })
  })

  /** Правка кандидата открывает окно на заведённой карточке, а не на пустой
   *  форме: иначе «Сохранить» завело бы вторую, ручную карточку того же
   *  фильма. */
  async function edit(view) {
    const full = view.item_id ? view : await asked(view)
    if (full) onedit(full)
  }

</script>

