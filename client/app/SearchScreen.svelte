  <!-- Список убранного. Отметок, оценок и разворота у строки нет: возвращается
       не карточка, а память о ней. -->
  <div class="feed">
    {#each views as view (keyOf(view))}
      <Gone {view} onrestore={(one) => restore(one).catch(lost)} />
    {/each}
  </div>
