<!-- Корень страницы: шапка, стопка разделов и плашка сообщений. -->
<script>
  import CardModal from './CardModal.svelte'
  import CardTagsModal from './CardTagsModal.svelte'
  import Confirm from '$components/Confirm.svelte'
  import FiltersModal from './FiltersModal.svelte'
  import LibraryScreen from './LibraryScreen.svelte'
  import ReviewModal from './ReviewModal.svelte'
  import SearchScreen from './SearchScreen.svelte'
  import StatsScreen from './StatsScreen.svelte'
  import Topbar from './Topbar.svelte'
  import Scrollarea from '$components/Scrollarea.svelte'
  import Snack from '$components/Snack.svelte'
  import { call, numbered } from '$api/bridge.js'
  import { isEmpty } from '$state/filters.js'
  import { question } from '$state/removal.js'
  import { newSession, withClearedFilter, withFilters, withForgotten, withMark,
    withSection } from '$state/session.js'
  import { complaining, reported } from './trouble.js'
  import { forgetCard } from './visible.js'

  // Раздел, которого здесь нет, откроется пустым и молча: `Screen` станет
  // `undefined`, а Svelte на этом не жалуется. Значения обязаны совпадать с
  // теми, что перебирает шапка и знает `sorting.js`.
  const SCREENS = {
    search: SearchScreen,
    // Оба раздела библиотеки — один экран: различает их `session.section`,
    // и он же уезжает в запрос.
    rated: LibraryScreen,
    wishlist: LibraryScreen,
    stats: StatsScreen,
  }

  // Фильмам достаётся значение по умолчанию из палитры, поэтому его тут нет:
  // положить одно значение в два места значит дать ему разойтись. Остальные два
  // подставляются токенами, а не литералами — цвет живёт в палитре.
  const ACCENTS = { series: 'var(--accent-series)', game: 'var(--accent-game)' }

  let session = $state(newSession())

  // Запрос живёт здесь, а не в разделе: набирают его в шапке, а показывает
  // выдачу поиск, и общего у них только это состояние.
  //
  // Своим объектом, а не строкой: повторный Enter с той же строкой обязан
  // спросить заново — иначе после отказа сети повторить поиск было бы нечем.
  let query = $state(null)

  // Клик по имени: домен и строка сущности. Живёт рядом с запросом и по той же
  // причине — жест делают в карточке, а показывает выдачу поиск.
  let person = $state(null)

  // Набранное в шапке. Обычно оно её собственное, но снять его вправе сборка:
  // клик по имени отменяет строку, и оставшийся в поле текст утверждал бы, что
  // выдача по нему.
  let typed = $state('')

  // Плашка одна на всё приложение, и говорят в неё разделы: своей они не
  // заводят.
  let trouble = $state(null)

  // Сколько оценок агрегаторов ждать. Спрашивается здесь, а не в каждом
  // разделе: зависит это от типа содержимого, а он общий, и два одинаковых
  // запроса разошлись бы молча.
  let expected = $state([])

  // Прокручивается область содержимого, и знает об этом только сборка. Ленте
  // она нужна корнем наблюдателя: иначе запас догрузки не действует.
  let content = $state()

  // Карточка, которой пишут рецензию, и записанное по ней.
  //
  // Сигнал несёт саму строку, а не номер: у ленты `patch` ищет по номеру, у
  // выдачи поиска — по паре «источник плюс идентификатор», и обе половины умеют
  // это сами. Момент — по той же причине, что у `saved` и `removed`: вторая
  // правка тем же текстом иначе эффект не разбудит.
  let reviewing = $state(null)
  let reviewed = $state(null)

  // Карточка, которой правят теги, и её метки, уже сохранённые.
  let tagging = $state(null)
  // Метки, доехавшие до ленты раньше, чем она перечитается: карточка обязана
  // показать их сразу. Накладываются производной, а не эффектом по ленте:
  // эффект, читающий и пишущий один список, — это бесконечный круг.
  //
  // Живут ровно до смены запроса и помнят его вместе с собой: перечитанная
  // лента привозит метки из базы, и держать поверх неё своё значит спорить с
  // ней. Ключом, а не эффектом по нему: эффект гасил бы наложение в тот же миг,
  // когда забвение меняет фильтры, то есть раньше, чем оно применилось.
  let tagged = $state({ asked: null, cards: {} })
  // Номера тегов, которых больше нет в наборе. Отдельно от `tagged`, потому что
  // метка обычно приехала из базы вместе с карточкой, и вычесть её надо у всех,
  // а не только у тронутых модалкой. Список не устаревает: удалённый тег не
  // возвращается, а его номер SQLite выдаст только новому тегу.
  let forgotten = $state([])

  // То, после чего метки приедут из базы сами. Собирается здесь, а не общим
  // `requestOf`: у поиска и статистики нет ни порядка, ни страницы, и
  // `requestOf` за них падает намеренно.
  //
  // Фильтров тут нет, и это не упущение. На их смену перечитывается лента, а
  // выдача поиска — нет: она отсеивается на месте, из того же списка. Считай
  // фильтр сменой запроса — и щелчок по метке, которую человек только что
  // поставил, гасил бы наложение: карточка возвращалась бы к прочитанным
  // меткам, не проходила бы собственный фильтр и пропадала из выдачи.
  const asked = $derived(JSON.stringify(
    [session.kind, session.section, session.sort]))

  const marks = $derived(tagged.asked === asked ? tagged.cards : {})

  // Плашка одна на приложение, и говорят в неё все четыре наложения и все
  // четыре раздела — одинаково.
  const complain = (text) => { trouble = { text } }

  // Своё сборка тоже не глотает: три её вызова моста — удаление, сводка и
  // ссылка — идут той же связкой «в журнал и на плашку», что и у разделов.
  const lost = complaining('сборка', complain)

  // Что открыто в окне карточки: `undefined` — закрыто, `null` — новая,
  // карточка — правка. Тремя состояниями, а не двумя: «окно открыто» и «окно
  // открыто на этой карточке» — разные вопросы, и признаком их не различить.
  let editing = $state(undefined)

  // Карточка, у которой спросили подтверждение удаления, вместе со сводкой:
  // что именно пропадёт, знает база, а не лента.
  let removing = $state(null)

  // Только что удалённая карточка. Раздел убирает её у себя, не перечитывая
  // ленту — страница читается с начала, и в длинном списке человек потерял бы
  // место, на котором стоял.
  //
  // Двух видов, и различает их номер: `{ item_id, at }` — удалённая из базы,
  // такую убирают у себя все разделы; `{ item_id: null, source, source_id, at }`
  // — строка выдачи, которую ещё не догрузили, и в базе её нет вовсе. Вторую
  // узнают по паре, и касается она только поиска: в библиотеке та же пара
  // указала бы на живую карточку.
  //
  // Сигналом, а не списком удалённых: `item` заведён без `AUTOINCREMENT`, и
  // номер SQLite выдаёт повторно — список прятал бы заведённую заново карточку,
  // получившую номер покойницы. Момент нужен по той же причине, что и записи:
  // удалив вторую карточку с тем же номером, номером эффект не разбудить.
  let removed = $state(null)

  // Только что записанная карточка: номер и момент. Раздел обязан показать её
  // свежей, а перечитывать всю ленту нельзя — человек потерял бы место, на
  // котором стоял.
  //
  // Объектом, а не номером: правя ту же карточку второй раз, номером эффект не
  // разбудить — значение то же самое, и раздел остался бы со старой.
  let saved = $state(null)

  // Какое наложение открыто, знает сборка: `null` либо признак с подписью.
  // Подпись едет от кнопки, которая окно открыла: заголовок окна и есть её
  // подпись, и вторым объявлением они разъехались бы молча.
  let modal = $state(null)

  // Плашки тут нет намеренно: список ожидаемых правит только кружки ожидания, и
  // говорить человеку про них нечего. Запись есть, как у всех: без неё «у моих
  // фильмов нет оценок агрегаторов» и «список ожидаемых не доехал» с экрана
  // неразличимы. Отказ при этом оставляет прежний список — если тип успели
  // сменить, кружки будут от прежнего типа, и найти это можно только в журнале.
  $effect(() => {
    numbered('world.expected', session.kind, { channel: 'expected' })
      .then((sources) => { expected = sources })
      .catch((error) => reported(error, 'ожидаемые оценки'))
  })

  // Акцент красит всю страницу, поэтому ставит его тот, кто страницей владеет,
  // а не шапка: она про свои три зоны. И следует он за состоянием, а не за
  // нажатием — иначе тип, пришедший откуда-то ещё, приехал бы со старым цветом.
  $effect(() => {
    const root = document.documentElement.style
    const accent = ACCENTS[session.kind]
    accent ? root.setProperty('--primary', accent) : root.removeProperty('--primary')
  })

  const Screen = $derived(SCREENS[session.section])


  /** Клик по имени открывает поиск по человеку, а не отдельный вид: та же
   *  лента, те же карточки, сначала своё и потом чужое.
   *
   *  Строка снимается вместе с набранным: пока человек стоит, раздел её не
   *  читает — но сними человека, и старая строка воскресила бы свою выдачу, а
   *  поле бы утверждало, что показано найденное по ней. Набранная после клика
   *  строка симметрично снимает человека: она отменяет жест, а не складывается
   *  с ним. */
  function byPerson(domain, entity_id) {
    forgetQuery()
    person = { domain, entity_id }
    session = withSection(session, 'search')
  }

  /** Набранная строка отменяет клик по имени: это другой жест, а не добавка к
   *  нему. */
  function searched(text) {
    person = null
    query = { text }
    session = withSection(session, 'search')
  }

  /** Строку снимают в трёх местах, и всюду одинаково: набранное и запрос — это
   *  одна вещь, показанная дважды.
   *
   *  Человека при этом не трогаем: поле у его выдачи и так пусто, а очистка
   *  начатого и брошенного поиска не повод убирать показанное. Сняв заодно и
   *  его, мы оставили бы раздел пустым навсегда — карточки, по имени с которой
   *  кликали, на экране уже нет. */
  function forgetQuery() {
    query = null
    typed = ''
  }

  /** Смена вкладки снимает набранную строку: поиски разных типов экранированы
   *  друг от друга — строка искала игры, и во вкладке сериалов её выдача уже
   *  про другое. Решено пользователем 02.08.2026 на живом приложении, где
   *  очищенное поле показывало сериалы по игровому запросу.
   *
   *  Клик по имени вкладку переживает, и это подтверждено тогда же: работы
   *  человека другого типа смотрят именно переключением вкладки. */
  function switched(next) {
    if (next.kind !== session.kind) forgetQuery()
    session = next
  }

  /** Повторное нажатие по горящей кнопке сбрасывает свой признак, а не
   *  открывает модалку: так в макете, где у каждого из трёх фильтров свой
   *  `isActive()` и свой `reset()`. */
  function filter(field, title) {
    if (!isEmpty(session.filters, field)) {
      session = withClearedFilter(session, field)
      return
    }
    modal = { field, title }
  }

  /** Тега больше нет в наборе, и помнить его номер не должен никто: ни отбор
   *  ленты, ни метки на её карточках.
   *
   *  Перечитыванием ленты это не лечится: страница читается с начала, и в
   *  длинном списке человек потерял бы место, на котором стоял. */
  function forget(id) {
    session = withForgotten(session, 'tags', id)
    forgotten = [...forgotten, id]
  }

  /** Сводка приходит от базы: сколько тегов, есть ли оценка и закладка.
   *  Спрашивается до вопроса, а не после согласия, — иначе перечислять в
   *  вопросе было бы нечего. Не приехала — вопроса не будет вовсе: удалять,
   *  не сказав что пропадёт, хуже, чем не удалить. */
  function askRemoval(view) {
    // Строку, которую ещё не догрузили, спрашивать не о чем: в базе её нет, и
    // терять нечего — она просто уходит из выдачи до следующего запроса.
    if (!view.item_id) {
      removed = { item_id: null, source: view.source,
                  source_id: view.source_id, at: Date.now() }
      return
    }
    call('library.deletion_summary', view.item_id)
      .then((summary) => { removing = { view, summary } })
      .catch((error) => lost(error, 'Не удалось прочитать карточку'))
  }

  /** Порядок двух файлов базы знает бэкенд: обложка уходит первой.
   *
   *  Номер забывается и памятью показанных: SQLite выдаёт его повторно, и
   *  заведённая заново карточка иначе считалась бы уже спрошенной. */
  function remove() {
    const { item_id } = removing.view
    removing = null
    call('library.delete', item_id)
      .then(() => {
        forgetCard(item_id)
        removed = { item_id, at: Date.now() }
      })
      .catch((error) => lost(error, 'Не удалось удалить карточку'))
  }

  /** Ссылку открывает системный браузер: окно приложения без адресной строки, и
   *  вернуться из Кинопоиска было бы нечем. Отказ у этого свой — чужая схема
   *  адреса заведена в мосте отдельным классом ровно затем, чтобы плашка
   *  назвала причину, а не промолчала. */
  function open(url) {
    call('world.open', url).catch((error) =>
      lost(error, 'Не удалось открыть ссылку'))
  }
</script>

<div class="app">
  <main class="app__main">
    <Topbar {session} bind:typed
            onsession={switched}
            onsearch={(text) => { if (text) { searched(text) } else { forgetQuery() } }}
            onadd={() => { editing = null }} onfilter={filter} />

    <!-- Прокручивается содержимое, а не страница, и полоса у него своя: она
         идёт у края окна, а не по краю колонки с карточками. -->
    <Scrollarea bind:box={content}>
      {#snippet children()}
        <!-- `{#key}` здесь не украшение: без него Svelte переиспользует ту же
             секцию, проявление не проигрывается, и переход между разделами
             становится мгновенной подменой. -->
        <!-- Столбцы гистограммы отрастают из пола при каждом заходе на раздел,
             а не один раз за всё время работы. Перезапускать анимацию руками не
             надо: `{#key}` выше пересоздаёт секцию целиком, и вместе с ней —
             каждый столбец. -->
        {#key session.section}
          <section class="view is-shown"
                   class:is-drawing={session.section === 'stats'}>
            <!-- Метка и человек решаются здесь, а не в разделе: клик по жанру
                 включает фильтр, клик по имени открывает поиск по человеку — и
                 то и другое меняет общее состояние. -->
            <Screen {session} {query} {person} {expected} root={content}
                    ontrouble={complain}
                    onmark={(field, id) => { session = withMark(session, field, id) }}
                    onperson={byPerson}
                    onopen={open}
                    onedit={(view) => { editing = view }}
                    ondelete={askRemoval}
                    {saved} {removed} {reviewed}
                    tagged={marks} {forgotten}
                    onreview={(view) => { reviewing = view }}
                    ontag={(view) => { tagging = view }} />
          </section>
        {/key}
      {/snippet}
    </Scrollarea>
  </main>

  <!-- `{#key}` не украшение: без него смена признака переиспользует то же окно
       вместе с уже прочитанным чужим списком, и щелчок по строке в этот
       промежуток ставит фильтр по жанру номером тега. -->
  {#if modal}
    {#key modal.field}
      <FiltersModal field={modal.field} title={modal.title} kind={session.kind}
                    filters={session.filters}
                    onfilters={(next) => { session = withFilters(session, next) }}
                    onforget={forget}
                    ontrouble={complain}
                    onclose={() => { modal = null }} />
    {/key}
  {/if}

  <!-- `{#key}` по той же причине, что у соседей: подмена карточки под окном
       переиспользовала бы его вместе с уже набранным чужим текстом. -->
  {#if reviewing}
    {#key reviewing.item_id}
      <ReviewModal view={reviewing} ontrouble={complain}
                   onsaved={(card, fields) => { reviewed = { view: card, fields,
                                                            at: Date.now() } }}
                   onclose={() => { reviewing = null }} />
    {/key}
  {/if}

  <!-- `{#key}` по той же причине, что у соседа: подмена карточки под окном
       переиспользовала бы его вместе с уже прочитанным чужим набором и уже
       проставленными отметками. -->
  {#if tagging}
    {#key tagging.item_id}
      <CardTagsModal view={tagging}
                   onview={(tags) => { tagged = { asked,
                                                 cards: { ...marks,
                                                          [tagging.item_id]: tags } } }}
                   ontrouble={complain}
                     onclose={() => { tagging = null }} />
    {/key}
  {/if}

  <!-- `{#key}` по той же причине, что у соседей: без него правка второй
       карточки переиспользовала бы окно вместе с уже набранной формой первой. -->
  {#if editing !== undefined}
    {#key editing?.item_id ?? 'new'}
      <CardModal view={editing} kind={session.kind} ontrouble={complain}
                 onsave={(item_id) => { saved = { item_id, at: Date.now() }
                                        editing = undefined }}
                 onclose={() => { editing = undefined }} />
    {/key}
  {/if}

  <!-- Красным светится необратимое: карточка уходит вместе с оценкой, тегами и
       закладкой, и вернуть их нечем. -->
  {#if removing}
    <Confirm label="Удалить карточку" ok="Удалить" danger
             text={question(removing.view, removing.summary)}
             onyes={remove} onclose={() => { removing = null }} />
  {/if}

  <Snack message={trouble} />
</div>
