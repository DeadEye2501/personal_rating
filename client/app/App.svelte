<!-- Корень страницы: показывает, дождалась ли она моста. -->
<script>
  // Заглушка до задачи 4: там появится `api/bridge.js`, единственное место
  // страницы, которое знает про `window.pywebview`, и корень станет звать его.

  // Мост приезжает двумя внедрениями: первое объявляет `window.pywebview` с
  // пустым `api`, второе заполняет его и только тогда шлёт `pywebviewready`.
  // Между ними сам объект уже есть, а звать в нём нечего — отсюда проверка по
  // содержимому, а не по существованию.
  const arrived = () => Object.keys(window.pywebview?.api ?? {}).length > 0

  // Начальное значение читается сразу, а не только по событию: внедрение идёт
  // на каждой навигации, и подписка, поставленная после него, события уже не
  // увидит.
  let ready = $state(arrived())
  window.addEventListener('pywebviewready', () => { ready = true })
</script>

<div class="app">
  <p>{ready ? 'мост на месте' : 'жду мост'}</p>
</div>
