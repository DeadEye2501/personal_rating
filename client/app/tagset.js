/* Правка самого набора тегов: удалить и переставить. */

/* Отдельно от модалки, которая его показывает: та перебирает состояния строк и
 * собирает разметку, а здесь — то, что уезжает в базу. Сборка по решению
 * проекта только собирает, а эти три вызова к тому же единственные во всём
 * фронте, которые правят чужой набор, а не своё состояние.
 *
 * Заведение тега лежит рядом, в `tags.js`: у него свой отказ — занятое имя, —
 * и потребителей у него двое. */

import { call } from '$api/bridge.js'

/** Сколько карточек носит тег. Спрашивается перед удалением: у тега с
 *  носителями оно подтверждается с их числом, ничей уходит молча. */
export const wearers = (id) => call('marks.tag_usage', id)

/** Набор без удалённого тега. Строка убирается по номеру, а не по месту:
 *  список успевает переехать перетаскиванием между вопросом и ответом.
 *
 *  Отказ пробрасывается: набор без строки при живом теге в базе означал бы
 *  «удаление работает через раз» — следующий заход в окно вернул бы её. */
export async function dropped(rows, id) {
  await call('marks.delete_tag', id)
  return rows.filter((row) => row.id !== id)
}

/** Порядок набора в базу. Без него перестановка живёт до закрытия окна:
 *  `position` пишет база. */
export const ordered = (rows, kind) =>
  call('marks.reorder_tags', kind, rows.map((row) => row.id))
