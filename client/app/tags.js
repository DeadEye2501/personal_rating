/* Заведение тега с общим отказом. */

/* Лежит в сборке, а не в `state/`: слой состояния считает переходы и в
 * `api/` не ходит вовсе — это записанное правило границы, и держит его
 * машинная проверка на каждой записи файла. Обе потребительницы тоже
 * здесь, и сосед по слою — `trouble.js` — заведён по той же причине. */

import { call } from '$api/bridge.js'
import { reported } from './trouble.js'

// Род отказа собирается из имени класса `TagExists` — так его называет
// `bridge/answer.py:kebab`. Пару сторожит `tests/bridge/test_page_contract.py`.
const TAG_EXISTS = 'tag-exists'

/** Новый тег или `null`, если завести не вышло.
 *
 *  Отказ обрабатывается здесь, а не у каждого вызывающего: занятое имя — это
 *  нормальный ход событий, и сказать про него надо одинаково в обоих местах,
 *  откуда теги заводят. Остальные отказы называются иначе: оборванный мост,
 *  объявивший имя занятым, отправил бы человека искать тег, которого нет. */
export async function created(kind, name, ontrouble) {
  try {
    const id = await call('marks.create_tag', kind, name)
    return { id, name }
  } catch (error) {
    // Через общий `reported`, а не прямо в плашку: иначе оборванный мост
    // назвал бы себя человеку и не оставил бы в журнале ни рода, ни следа.
    const text = error.kind === TAG_EXISTS ? 'Такой тег уже есть'
                                           : 'Не удалось завести тег'
    reported(error, 'заведение тега', () => ontrouble(text))
    return null
  }
}
