import { describe, expect, it } from 'vitest'

import { heightsOf } from '$state/histogram.js'

describe('высоты столбцов', () => {
  it('считаются от пика, а не от суммы', () => {
    // От суммы самый высокий столбец занял бы долю процентов, и гистограмма
    // выглядела бы плоской на любой библиотеке.
    const shares = heightsOf([{ score: 1, count: 5 }, { score: 2, count: 10 }])

    expect(shares).toEqual([0.5, 1])
  })

  it('пик не зависит от того, где он стоит', () => {
    // Иначе доли считались бы от последнего столбца или от первого, а не от
    // самого высокого, и на убывающем наборе всё выше единицы не заметил бы
    // никто.
    const shares = heightsOf([{ score: 1, count: 10 }, { score: 2, count: 5 }])

    expect(shares).toEqual([1, 0.5])
  })

  it('пустой столбец имеет нулевую долю, а не отсутствует', () => {
    // Десять столбцов стоят всегда: пропущенный сдвинул бы шкалу, и седьмая
    // оценка оказалась бы под шестой подписью.
    const shares = heightsOf([{ score: 1, count: 0 }, { score: 2, count: 4 }])

    expect(shares).toEqual([0, 1])
  })

  it('на пустой библиотеке не делит на ноль', () => {
    // Иначе десять `NaN` уехали бы в `height` строкой «NaN%».
    expect(heightsOf([{ score: 1, count: 0 }, { score: 2, count: 0 }]))
      .toEqual([0, 0])
  })

  it('доля остаётся дробью, а не округляется к соседнему столбцу', () => {
    // Три из семи — 0.428…, и до целых процентов её доводит уже показ. Округли
    // здесь хоть до десятых, и соседние столбцы сравнялись бы по высоте.
    const shares = heightsOf([{ score: 1, count: 3 }, { score: 2, count: 7 }])

    expect(shares[0]).toBe(3 / 7)
  })

  it('ничья на пике поднимает оба столбца до верха', () => {
    // Пик один на набор, а не «первый из равных»: второй такой же обязан
    // встать вровень, а не ниже.
    expect(heightsOf([{ score: 1, count: 4 }, { score: 2, count: 4 }]))
      .toEqual([1, 1])
  })
})
