import { describe, expect, it } from 'vitest'

import { wordEnd } from '$state/trim.js'

const LINE = 'Династия Таргариенов начинает борьбу'

describe('обрезка текста по границе слова', () => {
  it('предел посреди слова отступает к предыдущей границе', () => {
    // Ради этого модуль и заведён: замер даёт длину в знаках, и приходится она
    // на середину слова чаще, чем на пробел. Огрызок «начи», к которому
    // вплотную встанет кнопка, — это то, чего быть не должно.
    expect(wordEnd(LINE, 25)).toBe('Династия Таргариенов')
  })

  it('слово, кончившееся ровно на пределе, остаётся целым', () => {
    // Обратная ошибка, и она не видна на предыдущей проверке: отступать всегда
    // значило бы выбрасывать слово, которое влезло.
    expect(wordEnd(LINE, 20)).toBe('Династия Таргариенов')
  })

  it('неразрывный пробел — тоже граница', () => {
    // У TMDB в описаниях он встречается: тринадцать штук на девятьсот знаков
    // записанного ответа. Ищи границу одним лишь обычным пробелом — и текст
    // либо потеряет лишнее слово, либо оборвётся посреди него.
    expect(wordEnd('Династия Таргариенов начинает', 25))
      .toBe('Династия Таргариенов')
    expect(wordEnd('Династия Таргариенов', 12)).toBe('Династия')
  })

  it('длинное слово без пробелов режет как есть', () => {
    // Обрезать нечего по границам, а показать что-то надо: пустая строка на
    // месте синопсиса — это потеря, а не аккуратность.
    expect(wordEnd('Абракадабра', 5)).toBe('Абрак')
  })

  it('предел длиннее текста отдаёт текст целиком', () => {
    expect(wordEnd('Коротко', 99)).toBe('Коротко')
  })

  it('снимает знаки препинания на разрыве', () => {
    // «трон, … ещё» читается как перечисление, которого нет: запятая обещает
    // продолжение в той же строке.
    expect(wordEnd('Борьба за трон, и не только', 15)).toBe('Борьба за трон')
  })
})
