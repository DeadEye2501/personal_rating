import { describe, expect, it } from 'vitest'

import { retagged } from '$state/marking.js'

const card = (item_id, tags) => ({ item_id, title: `№${item_id}`, tags })
const tag = (id, name) => ({ id, name, kind: 'movie' })

describe('метки поверх прочитанного', () => {
  it('правка набора на карточке заменяет её метки целиком', () => {
    // Модалка отдаёт то, что теперь на карточке, а не разницу: снятая метка
    // иначе висела бы до перечитывания ленты.
    //
    // Прочитанное при этом остаётся нетронутым: правка на месте — это запись в
    // собственную зависимость производной, и наложение стало бы необратимым.
    const views = [card(1, [tag(7, 'нуар')])]

    const shown = retagged(views, { 1: [tag(9, 'пересмотреть')] }, [])

    expect(shown[0].tags).toEqual([tag(9, 'пересмотреть')])
    expect(views[0].tags).toEqual([tag(7, 'нуар')])
  })

  it('снятая последняя метка исчезает с карточки', () => {
    // Пустой набор — обычный жест: сняли единственную галку в модалке. Считать
    // его «правки нет» значит оставить метку висеть до перечитывания ленты.
    const views = [card(1, [tag(7, 'нуар')])]

    const shown = retagged(views, { 1: [] }, [])

    expect(shown[0].tags).toEqual([])
  })

  it('забытый тег уходит со всех карточек, а не только с правленой', () => {
    // Тег удаляют из набора, а метки уже приехали из базы вместе с карточками:
    // не вычесть их — и клик по осиротевшей метке поставит фильтр по мёртвому
    // номеру, лента опустеет, а выключить его будет нечем.
    const views = [card(1, [tag(7, 'нуар')]), card(2, [tag(7, 'нуар')])]

    const shown = retagged(views, {}, [7])

    expect(shown.map((view) => view.tags)).toEqual([[], []])
  })

  it('правка и забвение действуют вместе', () => {
    // Тег сняли с набора, пока модалка карточки была открыта: правка привезла
    // его обратно, и вычесть его надо и оттуда.
    const views = [card(1, [tag(7, 'нуар')])]

    const shown = retagged(views, { 1: [tag(7, 'нуар'), tag(9, 'ещё')] }, [7])

    expect(shown[0].tags).toEqual([tag(9, 'ещё')])
  })

  it('нетронутая карточка отдаётся той же самой, а тронутая — новой', () => {
    // Той же самой — чтобы правка одной метки не перезапускала производные во
    // всех полусотне карточек ленты. Новой — потому что иначе это правка на
    // месте, то есть запись в собственную зависимость производной.
    const views = [card(1, [tag(7, 'нуар')]), card(2, [tag(7, 'нуар')])]

    const shown = retagged(views, { 2: [tag(9, 'ещё')] }, [])

    expect(shown[0]).toBe(views[0])
    expect(shown[1]).not.toBe(views[1])
  })
})
