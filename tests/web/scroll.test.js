import { describe, expect, it } from 'vitest'

import { thumbOf } from '$state/scroll.js'

describe('своя полоса прокрутки', () => {
  it('на коротком содержимом полосы нет вовсе', () => {
    expect(thumbOf(400, 300, 0)).toBe(null)
    expect(thumbOf(400, 400, 0)).toBe(null)
  })

  it('пиксель разницы полосы не заводит, а два — заводят', () => {
    // Высоты браузер отдаёт целыми, и разница в пиксель бывает округлением, а
    // не содержимым: без порога снизу список, совпавший с областью, получал бы
    // вечный ползунок во всю дорожку.
    expect(thumbOf(400, 401, 0)).toBe(null)
    expect(thumbOf(400, 402, 0)).not.toBe(null)
  })

  it('высота ползунка — доля видимого от всего', () => {
    // Видно четверть — ползунок в четверть области.
    expect(thumbOf(400, 1600, 0).height).toBe(100)
  })

  it('короткий ползунок не даёт себя ухватить, и потому у него есть предел', () => {
    // Доля дала бы четыре пикселя: на списке в сто строк это не мишень.
    expect(thumbOf(400, 40000, 0).height).toBe(28)
  })

  it('в начале списка ползунок стоит вверху области', () => {
    expect(thumbOf(400, 1600, 0).offset).toBe(0)
  })

  it('на середине списка ползунок стоит на середине дорожки', () => {
    // Дорожка — это область без самого ползунка: 400 − 100.
    expect(thumbOf(400, 1600, 600).offset).toBe(150)
  })

  it('внизу списка ползунок стоит внизу области, а не за её краем', () => {
    const found = thumbOf(400, 1600, 1200)

    expect(found.offset).toBe(400 - found.height)
  })

  it('пиксель курсора стоит больше пикселя содержимого', () => {
    // Иначе ползунок отставал бы от мыши тем сильнее, чем длиннее список.
    expect(thumbOf(400, 1600, 0).scale).toBe(4)
  })

  it('у подпёртого снизу ползунка масштаб считается по его дорожке', () => {
    // Доля от всего дала бы 100 при нужных 106.45: ползунок, доведённый до
    // низа дорожки, не довёл бы список до конца.
    expect(thumbOf(400, 40000, 0).scale).toBeCloseTo(39600 / 372, 6)
  })
})
