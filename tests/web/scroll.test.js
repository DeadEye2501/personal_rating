import { describe, expect, it } from 'vitest'

import { thumbFor, thumbOf } from '$state/scroll.js'

describe('своя полоса прокрутки', () => {
  it('на коротком содержимом полосы нет вовсе', () => {
    // Содержимое короче области и вровень с ней: сравнение по строгому «меньше»
    // оставило бы вровень стоящему списку вечный ползунок во всю дорожку.
    expect(thumbOf(400, 300, 0)).toBe(null)
    expect(thumbOf(400, 400, 0)).toBe(null)
  })

  it('пиксель разницы полосы не заводит, а два — заводят', () => {
    // Высоты браузер отдаёт целыми, и разница в пиксель бывает округлением, а
    // не содержимым: без порога снизу список, совпавший с областью, получал бы
    // вечный ползунок во всю дорожку.
    expect(thumbOf(400, 401, 0)).toBe(null)
    expect(thumbOf(400, 402, 0)).not.toBe(null)
  })

  it('высота ползунка — доля видимого от всего', () => {
    // Видно четверть — ползунок в четверть области.
    expect(thumbOf(400, 1600, 0).height).toBe(100)
  })

  it('короткий ползунок не даёт себя ухватить, и потому у него есть предел', () => {
    // Доля дала бы четыре пикселя: на списке в сто строк это не мишень.
    expect(thumbOf(400, 40000, 0).height).toBe(28)
  })

  it('в начале списка ползунок стоит вверху области', () => {
    // Не только ноль: то же самое на подпёртом снизу ползунке, где дорожка
    // считается иначе, — иначе проверка держится на умножении на ноль и
    // переживает любую подмену внутри доли.
    expect(thumbOf(400, 1600, 0).offset).toBe(0)
    expect(thumbOf(400, 40000, 0).offset).toBe(0)
  })

  it('на середине списка ползунок стоит на середине дорожки', () => {
    // Дорожка — это область без самого ползунка: 400 − 100.
    expect(thumbOf(400, 1600, 600).offset).toBe(150)
  })

  it('внизу списка ползунок стоит внизу области, а не за её краем', () => {
    const found = thumbOf(400, 1600, 1200)

    expect(found.offset).toBe(400 - found.height)
  })

  it('высоту области берёт дробной, а не округлённой', () => {
    // `clientHeight` целое и округляет вверх: при настоящих 1059.6 он отдаёт
    // 1060, и доведённый до низа ползунок встаёт на 0.4 пикселя ниже своей
    // дорожки. Прятать переполнение от полосы до `html` некому, и страница
    // получает вторую полосу прокрутки, которая ничего не прокручивает.
    // Числа замерены на живом окне 04.08.2026.
    // Три величины разные нарочно: с одинаковыми проверка стала бы тавтологией
    // — сравнением довода с ним же самим.
    const box = { clientHeight: 1060, scrollHeight: 151736, scrollTop: 150676,
                  getBoundingClientRect: () => ({ height: 995.4 }) }
    const sized = { borderBoxSize: [{ blockSize: 1059.6 }] }

    const found = thumbFor(box, sized)

    expect(found.offset + found.height).toBeLessThanOrEqual(1059.6)
    // От `clientHeight` вышло бы ровно 1032, от видимой высоты — 967.
    expect(found.offset).toBeCloseTo(1031.597, 3)
  })

  it('высоту области берёт из довода, а не с самой коробки', () => {
    // Пока окно въезжает анимацией `scale(.94)`, `getBoundingClientRect()`
    // отдаёт высоту, сжатую превращением, а `scrollHeight` остаётся вёрстанным.
    // Снятый в этот миг ползунок объявляется нужным там, где прокручивать
    // нечего, и остаётся таким навсегда: превращение не будит ни наблюдателя
    // размера, ни прокрутку. Числа замерены на живом окне 24.08.2026 — ползунок
    // 263.3 при области 298, то есть ровно 298 × 0.94².
    // `clientHeight` под превращением остаётся вёрстанным, сжата только
    // видимая высота: 298 × 0.94 = 280.12.
    const box = { clientHeight: 298, scrollHeight: 298, scrollTop: 0,
                  getBoundingClientRect: () => ({ height: 280.12 }) }
    const sized = { borderBoxSize: [{ blockSize: 298 }] }

    expect(thumbFor(box, sized)).toBe(null)
  })

  it('пиксель курсора стоит больше пикселя содержимого', () => {
    // Иначе ползунок отставал бы от мыши тем сильнее, чем длиннее список.
    expect(thumbOf(400, 1600, 0).scale).toBe(4)
  })

  it('у подпёртого снизу ползунка масштаб считается по его дорожке', () => {
    // Доля от всего дала бы 100 при нужных 106.45: ползунок, доведённый до
    // низа дорожки, не довёл бы список до конца.
    expect(thumbOf(400, 40000, 0).scale).toBeCloseTo(39600 / 372, 6)
  })
})
