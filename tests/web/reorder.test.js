import { describe, expect, it } from 'vitest'

import { dragged } from '$state/reorder.js'

/** Середины строк одинаковой высоты: первая с 0 до 20, вторая с 20 до 40. */
const middles = (count) => Array.from({ length: count }, (_, at) => at * 20 + 10)

describe('перестановка строки', () => {
  it('строка едет вниз через все остальные', () => {
    // Курсор ниже середины последней — строка обязана оказаться в конце.
    expect(dragged(['а', 'б', 'в'], 0, middles(3), 55)).toEqual(['б', 'в', 'а'])
  })

  it('строка едет вверх', () => {
    expect(dragged(['а', 'б', 'в'], 2, middles(3), 5)).toEqual(['в', 'а', 'б'])
  })

  it('на один шаг вниз — обмен с соседкой, а не бросок в конец', () => {
    // Курсор прошёл середину второй строки (30), но не третьей (50).
    expect(dragged(['а', 'б', 'в'], 0, middles(3), 35)).toEqual(['б', 'а', 'в'])
  })

  it('не сдвинувшийся курсор оставляет порядок прежним', () => {
    expect(dragged(['а', 'б', 'в'], 1, middles(3), 25)).toEqual(['а', 'б', 'в'])
  })

  it('своя середина в счёт не идёт', () => {
    // Строка едет под курсором, и, спрошенная о себе, она отвечала бы сама
    // себе: каждое движение вниз промахивалось бы на строку. Проверяется на
    // пяти, а не на трёх: в конце списка `splice` зажимает промах, и на трёх
    // ошибка не видна вовсе. Курсор прошёл середину второй строки (30), но не
    // третьей (50), — значит место второе, а не третье.
    expect(dragged(['а', 'б', 'в', 'г', 'д'], 0, middles(5), 35))
      .toEqual(['б', 'а', 'в', 'г', 'д'])
  })

  it('граница перехода — ровно середина соседней строки', () => {
    // Пиксель выше середины — строка на месте, сама середина — уже переставлена.
    // Так в макете (`pointerY < середина`), и пара нужна с обеих сторон: одна
    // проверка не отличает `<` от `<=`, а разница в пиксель на границе даёт
    // мигание туда-обратно.
    expect(dragged(['а', 'б', 'в'], 0, middles(3), 29)).toEqual(['а', 'б', 'в'])
    expect(dragged(['а', 'б', 'в'], 0, middles(3), 30)).toEqual(['б', 'а', 'в'])
  })

  it('не трогает исходный список', () => {
    // Порядок уезжает в базу отдельным вызовом, и при отказе показанное
    // откатывают на прежний список — тот самый, который нельзя было испортить.
    const before = ['а', 'б', 'в']
    dragged(before, 0, middles(3), 55)

    expect(before).toEqual(['а', 'б', 'в'])
  })
})
