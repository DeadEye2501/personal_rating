/** Адрес обложки: по номеру карточки и по адресу у источника. */

import { describe, expect, it } from 'vitest'

import { bySource, byItem, coverFor } from '$state/covers.js'

describe('адрес обложки', () => {
  it('своя карточка спрашивается по номеру', () => {
    expect(byItem(12)).toBe('/poster?item=12')
  })

  it('метка момента дописывается к адресу, а не заменяет его', () => {
    // Ручка отдаёт сутки кеша, а адрес от содержимого не зависит: без метки
    // перезалитая обложка осталась бы прежней до завтра.
    expect(byItem(12, 1700000000)).toBe('/poster?item=12&at=1700000000')
  })

  it('у кандидата номера нет, и обложка идёт через источник', () => {
    // Кандидат в базу ещё не попал: спросить его обложку можно только тем, чем
    // он сам себя называет.
    expect(bySource('tmdb', 'https://i.tmdb/p/x.jpg', 'movie'))
      .toBe('/poster?source=tmdb&url=https%3A%2F%2Fi.tmdb%2Fp%2Fx.jpg&kind=movie')
  })

  it('адрес источника уезжает закодированным целиком', () => {
    // В адресе обложки бывает и `&`, и `?`: подставленный как есть, он стал бы
    // вторым доводом ручки, и она получила бы обрезанный адрес.
    const asked = bySource('gog', 'https://x/y?a=1&b=2', 'game')

    expect(asked).toContain('%3Fa%3D1%26b%3D2')
    // Доводов ровно три: источник, кодированный адрес и тип. Раскодированный
    // адрес добавил бы четвёртый и пятый.
    expect(asked.split('&')).toHaveLength(3)
  })

  it('тип кандидата уезжает вместе с адресом', () => {
    // Без него ручка не знает формы: обложку чужой формы бэкенд приводит к
    // нашей, а у альбома она квадратная.
    expect(bySource('deezer', 'https://cdn/x.jpg', 'music')).toContain('kind=music')
  })
})

describe('обложка строки', () => {
  const own = { item_id: 12, kind: 'game', source: 'steam', source_id: '22490' }

  it('строка из базы получает метку сеанса, а не свою', () => {
    // Строку раздел перечитывает из базы на каждом заходе, а `CardView` поля
    // под метку не объявляет вовсе — метка, положенная в строку, теряется на
    // первом же перечитывании. Так перезалитая обложка и возвращалась к
    // прежней: адрес выходил тот же, а ручка отдаёт сутки кеша.
    expect(coverFor(own, 1700000000)).toBe('/poster?item=12&at=1700000000')
  })

  it('своя метка строки ничего не решает', () => {
    // Сторож того же правила с другой стороны: две одинаковые строки, из
    // которых одна помнит собственный момент, обязаны дать один адрес.
    expect(coverFor({ ...own, cover: 1699999999 }, 0)).toBe(coverFor(own, 0))
  })

  it('без перезаливки метки нет: кеш нужен, пока картинка та же', () => {
    // Метка на каждом показе выключила бы кеш совсем — обложка качалась бы
    // заново на каждую перерисовку ленты.
    expect(coverFor(own, 0)).toBe('/poster?item=12')
  })

  it('кандидат идёт через источник, и метка его не касается', () => {
    // В базе его нет, спрашивать по номеру нечего; кеша у чужого адреса своя
    // судьба, и метка сеанса к ней отношения не имеет.
    const candidate = { item_id: null, kind: 'movie', source: 'tmdb',
                        poster_url: 'https://i.tmdb/p/x.jpg' }

    expect(coverFor(candidate, 1700000000))
      .toBe('/poster?source=tmdb&url=https%3A%2F%2Fi.tmdb%2Fp%2Fx.jpg&kind=movie')
  })

  it('кандидату без адреса обложки не из чего собрать ссылку', () => {
    // Заглушку рисует та же ветка, что и у сорвавшейся картинки, и пустая
    // строка ей нужна пустой: `src=""` браузер считает адресом страницы.
    expect(coverFor({ item_id: null, source: 'gog', poster_url: '' }, 0))
      .toBeFalsy()
  })
})
