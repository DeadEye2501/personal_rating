/** Адрес обложки: по номеру карточки и по адресу у источника. */

import { describe, expect, it } from 'vitest'

import { bySource, byItem, stampOf } from '$state/covers.js'

describe('адрес обложки', () => {
  it('своя карточка спрашивается по номеру', () => {
    expect(byItem(12)).toBe('/poster?item=12')
  })

  it('метка момента дописывается к адресу, а не заменяет его', () => {
    // Ручка отдаёт сутки кеша, а адрес от содержимого не зависит: без метки
    // перезалитая обложка осталась бы прежней до завтра.
    expect(byItem(12, 1700000000)).toBe('/poster?item=12&at=1700000000')
  })

  it('без перезаливки метки нет: кеш нужен, пока картинка та же', () => {
    // Метка на каждом показе выключила бы кеш совсем — обложка качалась бы
    // заново на каждую перерисовку ленты.
    expect(stampOf({ item_id: 12 })).toBe(0)
    expect(byItem(12, stampOf({ item_id: 12 }))).toBe('/poster?item=12')
  })

  it('момент берётся у самой карточки, а не у последнего сохранения', () => {
    // Перечитанная строка привозит момент вместе с собой. Хранить его отдельно
    // значит помнить одну карточку на всех: сохранил соседнюю — и окно правки
    // снова показывает вчерашнюю картинку.
    expect(stampOf({ item_id: 12, cover: 1700000000 })).toBe(1700000000)
  })

  it('у новой карточки момента нет, и спрашивать нечего', () => {
    // Окно заведения открывается без карточки вовсе: `null` тут обычное дело,
    // и обращение к полю уронило бы отрисовку окна.
    expect(stampOf(null)).toBe(0)
    expect(stampOf(undefined)).toBe(0)
  })

  it('у кандидата номера нет, и обложка идёт через источник', () => {
    // Кандидат в базу ещё не попал: спросить его обложку можно только тем, чем
    // он сам себя называет.
    expect(bySource('tmdb', 'https://i.tmdb/p/x.jpg'))
      .toBe('/poster?source=tmdb&url=https%3A%2F%2Fi.tmdb%2Fp%2Fx.jpg')
  })

  it('адрес источника уезжает закодированным целиком', () => {
    // В адресе обложки бывает и `&`, и `?`: подставленный как есть, он стал бы
    // вторым доводом ручки, и она получила бы обрезанный адрес.
    const asked = bySource('gog', 'https://x/y?a=1&b=2')

    expect(asked).toContain('%3Fa%3D1%26b%3D2')
    expect(asked.split('&')).toHaveLength(2)
  })
})
