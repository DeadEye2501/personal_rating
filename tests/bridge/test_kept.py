"""То, что не пролезает обратно через JSON, мост помнит у себя."""

from bridge.kept import Kept


def test_what_was_kept_comes_back():
    kept = Kept()
    kept.put(1, ["выдача"])
    assert kept.taken(1) == ["выдача"]


def test_a_stale_number_gets_nothing():
    """Страница набрала новый запрос, пока летел старый: второй шаг старой
    операции обязан уйти ни с чем, а не подставить чужую выдачу.

    Здесь же видно, что помнится ровно одно значение: словарь по номеру протекал
    бы на каждой брошенной операции, а брошенных больше, чем доведённых."""
    kept = Kept()
    kept.put(1, ["старое"])
    kept.put(2, ["новое"])

    assert kept.taken(1) is None
    assert kept.taken(2) == ["новое"]


def test_a_number_out_of_the_small_cache_is_still_recognised():
    """Сверяется значение, а не тождество. Номера приезжают разбором JSON, то
    есть двумя разными объектами, а малые целые в CPython общие — на единице с
    двойкой подмена не видна. С двести пятьдесят седьмой операции сверка по
    тождеству отвечала бы «устарело» всегда: ни внешней выдачи поиска, ни
    заведения кандидата, ни привязки по ссылке — и молча, потому что «устарело»
    законный ответ."""
    kept = Kept()
    first, second = int("1000"), int("1000")

    kept.put(first, ["выдача"])

    assert kept.taken(second) == ["выдача"]


def test_a_late_answer_does_not_take_the_cell_from_a_newer_one():
    """pywebview зовёт каждый метод в своём потоке, и ответ старой операции
    приезжает после того, как новая уже заняла ячейку. Номера растут, поэтому
    меньший — это опоздавший, и класть ему сюда нечего: страница получила бы
    «устарело» на заведение кандидата из выдачи, которую видит перед собой,
    и молча — `stale` помечен молчаливым.

    Раньше это держал сам домен поиска, и держал только у второго шага: у
    выдачи по человеку второго шага нет вовсе, а сеть и срок ожидания есть."""
    kept = Kept()
    kept.put(2, ["новое"])
    kept.put(1, ["опоздавшее"])

    assert kept.taken(2) == ["новое"]
    assert kept.taken(1) is None


def test_nothing_kept_is_not_a_failure():
    """Второй шаг без первого — обычное дело: операцию отменили."""
    assert Kept().taken(1) is None
