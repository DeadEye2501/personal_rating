"""Отказ операции: занятое имя, занятая идентичность, негодная картинка.

Почти всё это — нормальный ход событий, а не поломка: человек переименовал тег в
уже существующий, вставил ссылку на карточку, которая в библиотеке есть, выбрал
файлом не картинку. Живут в модели, а не рядом с тем, кто их бросает, потому что
клиенту из бэкенда открыты только `backend.model` и `backend.config`, а
различать их он обязан: плашка говорит разное.

Общий предок нужен мосту: он ловит один тип и переводит его в род отказа по
имени класса. Без предка седьмой отказ пришлось бы дописывать дважды."""


class Denied(Exception):
    """Операция отклонена, и это ожидаемо."""


class ItemExists(Denied):
    """Идентичность уже занята другой карточкой: пара (source, source_id) или
    любой из внешних идентификаторов. Второй повод поднимает привязка, и плашка
    про «эту карточку» на нём соврала бы — занята другая, а совпал IMDb ID."""


class TagExists(Denied):
    """Тег с таким именем в этом наборе уже есть."""


class WrongTagKind(Denied):
    """Тег одного типа содержимого на карточке другого."""


class IdentityTaken(Denied):
    """Пара (source, source_id) уже принадлежит другому человеку или студии."""


class BadImage(Denied):
    """Байты не разбираются как картинка."""


class Dangling(Denied):
    """Записи не к чему привязаться: строки, на которую она ссылается, нет.

    Почти всегда это удалённая карточка, и это гонка, а не ошибка пишущего: пока
    круг агрегаторов ехал двадцать секунд, её убрали из другого окна; то же у
    оценки и закладки, поставленных по уже нарисованной ленте.

    Реже — номер, которого нет в справочнике жанров, и это уже наша ошибка,
    попавшая в общий род отказов. Различить их база не даёт: она сообщает о
    нарушенном внешнем ключе, не называя, о каком именно, — поэтому имя говорит
    о следствии, а не о причине. Цена известна и принята: трассировка такой
    ошибки в журнал не попадёт, потому что мост отказы не записывает."""
