"""Язык, которым лента разговаривает с базой о разделах."""

from dataclasses import dataclass
from enum import StrEnum

from backend.model.kinds import Kind


class Section(StrEnum):
    """Разделы, которые спрашивают у базы. Поиска тут нет: он спрашивает и свою
    базу, и источники, и складывает две выдачи сам."""

    RATED = "rated"
    WISHLIST = "wishlist"


class Sort(StrEnum):
    """Критерии порядка, каждый в две стороны. Набор перебора зависит от
    раздела: в «Оценённых» четыре первых, в «Хочу посмотреть» — ADDED_AT и
    TITLE. Своей оценки у неоценённого не бывает, а девятое состояние
    понадобилось бы ровно одному разделу."""

    SCORE = "score"          # своя оценка
    RATED_AT = "rated_at"    # когда оценивал
    YEAR = "year"            # год выхода
    TITLE = "title"          # по алфавиту
    ADDED_AT = "added_at"    # когда отложил


@dataclass(frozen=True, slots=True)
class Order:
    """Критерий и сторона. Умолчание — сверху то, чего больше: высокие оценки,
    свежие даты, новые фильмы."""

    key: Sort
    descending: bool = True


@dataclass(frozen=True, slots=True)
class Filters:
    """Пустой набор — это «показать всё».

    Включённые складываются по «и» — и между признаками, и внутри признака:
    решение пользователя 02.08.2026, каждый выбранный сужает набор. Оценка и три
    шкалы игры — исключение, и не по решению, а по устройству: каждая из них у
    карточки одна, и «семь и восемь разом» не бывает ни у чего. Внутри такого
    признака выбранное складывается по «или», а между признаками остаётся «и»:
    «геймплей и нарратив равны 4 или 5» — это два условия, а не одно.

    Исключённые вычитаются последними, сильнее включённых и означают «ни одного
    из этих»: выбрал драму, исключил ужасы — получил драмы, среди которых нет ни
    одного ужаса, даже если он заодно и драма.

    Правило одно на обе стороны границы: в разделах его держит запрос, в выдаче
    поиска — `client/state/filters.js`, потому что спросить источник с фильтром
    нечем."""

    tag_ids: tuple[int, ...] = ()
    genre_ids: tuple[int, ...] = ()
    scores: tuple[int, ...] = ()   # столбцы гистограммы: ступень оценки, не сама оценка

    # Три шкалы игры — целыми ступенями: округлять тут нечего, их заводит ряд
    # звёзд. Невыставленная шкала не проходит отбор ни по одной ступени: она
    # никакая, а не низшая, — и общей оценке игры равной тоже не бывает.
    visual: tuple[int, ...] = ()
    narrative: tuple[int, ...] = ()
    gameplay: tuple[int, ...] = ()

    excluded_tag_ids: tuple[int, ...] = ()
    excluded_genre_ids: tuple[int, ...] = ()
    excluded_scores: tuple[int, ...] = ()

    excluded_visual: tuple[int, ...] = ()
    excluded_narrative: tuple[int, ...] = ()
    excluded_gameplay: tuple[int, ...] = ()


@dataclass(frozen=True, slots=True)
class Feed:
    """О чём спрашивает лента: раздел, тип содержимого, фильтры и порядок.

    Четыре вещи ходят вместе всегда: раздел без типа содержимого — это половина
    вопроса, а фильтры и порядок держит та же шапка, что и переключатель
    раздела."""

    section: Section
    kind: Kind
    filters: Filters
    order: Order


@dataclass(frozen=True, slots=True)
class Bucket:
    """Столбец гистограммы."""

    score: int
    count: int


@dataclass(frozen=True, slots=True)
class Histogram:
    """Столбцы и подвал под ними.

    `average` считает база по неокруглённым оценкам, а не клиент по столбцам:
    у игр оценка — среднее трёх шкал, и собранная из столбцов средняя разошлась
    бы с настоящей на полступени на карточку, в обе стороны."""

    buckets: tuple[Bucket, ...]
    total: int
    average: float | None   # пусто — считать нечего
