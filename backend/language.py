"""На каком языке написано название.

Ответ двоичный — русское или нет, — и этого хватает: у игры два места под имя,
`title` и `original_title`, и третьего нет. «Не русское» тут значит именно это, а
не «английское»: `Trüberbrook` и `FINAL FANTASY VII` попадают в одну корзину, и
обе уедут в поле английского названия. Решение пользователя 03.08.2026.

Определитель языка сюда не берётся: это зависимость и догадка, а для двух
языков, которые нас различают, проверка по алфавиту — не догадка, а факт.

Лежит в корне пакета по тому же доводу, что и `unique`: это не тип границы
слоёв, а приём, нужный и источникам, и сервисам. Источники в сервисы не ходят,
и общее для них живёт здесь.
"""

# Русский алфавит, а не кириллица целиком: украинское `і` и сербское `ђ` сюда не
# входят, и такие названия эта функция русскими не считает. Для нашей задачи это
# верно — русской локализацией они не являются.
RUSSIAN_LETTERS = frozenset("абвгдеёжзийклмнопрстуфхцчшщъыьэюя")

LATIN_LETTERS = frozenset("abcdefghijklmnopqrstuvwxyz")

__all__ = ["in_latin", "in_russian"]


def in_russian(name: str) -> bool:
    """Есть ли в названии хоть одна русская буква.

    Хоть одна, а не большинство: у «King's Bounty: Легенда о рыцаре» латиницей
    написана добрая половина, и это всё равно русское название."""
    return any(letter in RUSSIAN_LETTERS for letter in name.lower())


def in_latin(name: str) -> bool:
    """Есть ли в названии хоть одна латинская буква.

    Нужна отдельно от `in_russian`, потому что «не русское» и «английское» —
    разные вещи, а поле английского названия обещает второе. У old-games
    встречаются японские названия — `アンク2 ツタンカーメンの謎`, замерено 4 строки
    из 53, — и они не русские, но и не английские.

    Английское от французского эта функция не отличает и отличать не должна:
    выбор между ними решается порядком, а не письменностью."""
    return any(letter in LATIN_LETTERS for letter in name.lower())
