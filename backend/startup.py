"""Всё, чего не хватает приложению до первого запроса: рабочая папка с файлом
настроек и схема базы.

Решение пользователя 03.08.2026: «exe ДОЛЖЕН быть самодостаточным и сам
создавать все нужные файлы баз при первом старте». До него схему поднимал
человек командой `alembic upgrade head`, и без неё первый же запрос давал
«no such table: item».

Живёт в `backend/`, а не рядом с точкой входа: предмет здесь — база и настройки
бэкенда, а поток интерфейса про них не знает ничего.
"""

import logging
import shutil
from pathlib import Path

from alembic import command
from alembic.config import Config as AlembicConfig

logger = logging.getLogger(__name__)

# Шаблон настроек лежит файлом рядом с программой и в сборку едет как есть.
# Второго списка переменных в коде нет нарочно: он разошёлся бы с шаблоном
# молча, и в созданном файле не хватало бы переменной — а узнал бы об этом
# человек только по неработающему источнику.
TEMPLATE_NAME = ".env.example"

ALEMBIC_INI = "alembic.ini"


def ensure_env(data_dir: Path, template: Path) -> None:
    """Рабочая папка и файл настроек в ней.

    В лог отсюда почти ничего не пишется, и это не забывчивость: лога ещё нет —
    и уровень записи, и папка под `app.log` лежат в том самом файле, который тут
    заводится. Пропавший шаблон записывается всё равно: такая запись доедет хотя
    бы до `stderr`, а молчание про него не доедет никуда.

    Существующий файл не трогается ни при каком запуске: в нём заполненные
    руками ключи, и восстановить их человеку неоткуда.

    Шаблона может не оказаться — например, забыли положить в сборку. Это не
    повод не подняться: без ключей работают игры и вся своя библиотека, а без
    папки не работает ничего."""
    data_dir.mkdir(parents=True, exist_ok=True)
    settings = data_dir / ".env"
    if settings.exists():
        return
    if not template.is_file():
        logger.warning("шаблон настроек не найден: %s", template)
        return
    shutil.copyfile(template, settings)


def upgrade_schema(base_dir: Path | None = None) -> None:
    """Схема базы библиотеки — миграциями, а не объявлениями таблиц.

    Иначе пришлось бы звать `metadata.create_all`, и это второй источник правды
    о схеме: справочник жанров живёт **внутри** миграции, и созданные из
    объявлений таблицы были бы пусты — сорок семь жанров с правилами не завёл бы
    никто.

    Гоняется на каждом запуске, а не только на первом: узнать, первый ли он,
    можно только спросив саму базу, и ровно это alembic и делает — на поднятой
    схеме проход пустой.

    Путь к базе alembic берёт из окружения сам, через те же настройки, что и
    приложение, поэтому `.env` должен быть прочитан раньше."""
    root = base_dir or Path(__file__).resolve().parents[1]
    settings = AlembicConfig(str(root / ALEMBIC_INI))
    # Иначе `script_location` из `%(here)s` разъедется с рабочей папкой процесса:
    # под заморозкой она не та, где лежит `alembic.ini`.
    settings.set_main_option("script_location", str(root / "migrations"))
    # Лог остаётся нашим: подробности у той же метки в `migrations/env.py`.
    settings.attributes["configure_logger"] = False
    command.upgrade(settings, "head")
