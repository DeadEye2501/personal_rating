"""Снятие повторов с сохранением порядка."""

from collections.abc import Hashable, Iterable


def unique[T: Hashable](items: Iterable[T]) -> list[T]:
    """Повторы снимаются, порядок первых появлений остаётся.

    Порядок здесь не украшение, и `set` поэтому не годится: жанры стоят в
    карточке в ряд, оценки агрегаторов — тоже, а список ожидаемых источников
    задаёт, в каком виде вернётся ответ. Со множеством всё это перетасовывалось
    бы между показами.

    Лежит в корне пакета, а не в модели: это не тип границы слоёв, а приём,
    нужный всем трём слоям — хранилищу, источникам и сервисам."""
    return list(dict.fromkeys(items))
