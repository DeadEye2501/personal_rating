"""Издательство книги: как его пишут и как его узнавать.

Google Books отдаёт издателя свободной строкой, и одно издательство приезжает в
десятке написаний: «Издательство АСТ», «АСТ», `Ast`, `ACT` латиницей,
`Izdatel'stvo ACT`. Без приведения каждая книга заводит свою студию, и в базе их
четыре на одно издательство.

**Правило замерено на слепой разметке 23.08.2026**: 111 написаний из живой
выдачи по 54 запросам, судья видел только строки и не знал ни одного правила.
Приведение склеивает 13 пар из 18 при нуле ложных. Что не берётся: аббревиатура
против полного имени (`МИФ` против «Манн, Иванов и Фербер») — это словарь, а не
строка; две схемы транслитерации одного имени (`Rossmen` против `Rosman`);
латинское `c` против `к` (`DirectMEDIA` против «ООО ДиректМедиа»).
"""

import re
from collections import Counter
from functools import lru_cache

from backend.titles import flattened

__all__ = ["alike", "named", "publisher_key"]

# Юридическая форма: она про лицо, а не про имя, и в написании то есть, то нет.
#
# Слова здесь и ниже записаны **латиницей после транслитерации** — в том виде, в
# каком их встречает приведение. Порядок именно такой: сперва письменность, потом
# шелуха. Обратный порядок ловил «Издательство АСТ», но пропускал
# `Izdatel'stvo Ast` — то же слово латиницей, — и список пришлось бы держать в
# двух видах. Поймано третьей выборкой 23.08.2026.
FORMS = frozenset({
    "ooo", "zao", "oao", "pao", "ip", "nko", "llc", "ltd", "inc", "gmbh", "ag",
    "bv", "co", "corp", "company", "sa", "kg", "oy", "ab", "plc",
    # Те же формы других стран: чешская `s.r.o.`, индийская `Pvt Limited`,
    # австралийская `Pty`, итальянская `SpA`, французская `SAS`, голландская
    # `NV`, венгерская `Kft`, сербская `d.o.o.` Замер 23.08.2026 нашёл их прямо
    # в выдаче: `e-artnow sro`, `Manjul Publishing House Pvt Limited`.
    "sro", "pvt", "limited", "pty", "spa", "sas", "nv", "kft", "doo", "llp",
})

# Слова, которыми издательство называет себя издательством. Снимаются с обоих
# концов: по-русски приставкой, по-английски припиской.
WORDS = frozenset({
    "izdatelstvo", "izdatelstva", "izdatelskii", "izd", "vo", "dom",
    "publishing", "publishers", "publisher", "publications", "books", "book",
    "press", "house", "media", "group",
    # Союз — не имя: `Doubleday & Co` и `Doubleday` расходились на нём одном
    # после того, как `Co` стало сниматься (ревью 23.08.2026). Перечисление это
    # не рушит: `named` смотрит на союз до приведения, а не после.
    "and", "i",
})

# Буквы, у которых кириллица и латиница неразличимы на вид. Слово, набранное
# **целиком** из них, читается по-русски: `ACT` — это «АСТ», а не английское
# слово. Проверять надо всё слово: подмена по одной букве ломает настоящие
# латинские имена, `DirectMEDIA` превращался в `direstmedia`, а `Publishing` в
# `ruvlisning` — поймано замером 23.08.2026.
#
# Сверх того — только короткие и только капсом. Иначе подмена ловит настоящие
# английские слова, целиком сложенные из двойников, и коверкает их: обратная
# транслитерация меняет шесть букв из двенадцати (`c→s`, `h→n`, `p→r`, `x→h`,
# `b→v`, `y→u`), и `Hachette` становится `nasnette`, `Focus Home` — `focus
# nome`, а служебные `Co`, `Pty`, `Book` не узнаются вовсе и не снимаются:
# `Doubleday & Co` расходился с `Doubleday`. Поймано ревью 23.08.2026.
#
# Капс и длина — признаки того, ради чего подмена и заводилась: латиницей
# набирают **аббревиатуру** русского имени, `ACT` вместо «АСТ». Английское имя
# так не пишут, а служебное слово тем более.
LOOKALIKE = "acehkmoptxby"
_AS_CYRILLIC = str.maketrans(LOOKALIKE, "асенкмортхву")
_LOOKALIKE_LIMIT = 4

# Кириллица в латиницу — чтобы `ЛитРес` и `Litres` сошлись. Схема простая:
# сравнивать надо написания одного имени, а не читать вслух.
_TRANSLIT = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "i", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "sch", "ъ": "",
    "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}

# Имена, у которых служебное слово — часть имени, а не приписка. Записаны в том
# виде, в каком их встречает приведение: латиницей, строчными.
#
# Список исключений, а не сопоставлений: он ничего ни с чем не равняет, только
# запрещает обрезку. Без него `Penguin Group` сливается с `Penguin`, `Signal
# Books` с `Signal`, а `Ardis Publishers` (Анн-Арбор, русская литература) — с
# российским «АРДИС», который издаёт аудиокниги. Все три пары нашла слепая
# разметка проверочной выборки 23.08.2026, и все три — разные издательства.
#
# Цена названа: список знает только виденное. Новое издательство с таким же
# хвостом будет склеиваться с тёзкой, пока его сюда не впишут.
KEPT_WHOLE = frozenset({
    "penguin group",
    "signal books",
    "ardis publishers",
})

_PARENS = re.compile(r"[(\[].*?[)\]]")
# Имя в кавычках: всё вокруг него служебное. Так пишут «Издательский дом "Питер"», `Izd-Vo "Mik"`. Кавычки бывают трёх видов,
# и внутренние удвоенные тоже.
_QUOTED = re.compile(r'[«"“„]{1,2}([^«»"“”„]+)[»"”]{1,2}')
_JOINED = re.compile(r"\s(и|and)\s", re.I)
_SEPARATORS = re.compile(r"[,;:/]")
_DOUBLED = re.compile(r"(.)\1+")
# Сколько букв должно приходиться на одну правку, чтобы два написания считались
# одним издательством. Подобрано замером 23.08.2026 на слепой разметке 111
# написаний живой выдачи: при семи и больше ложных склеек нет вовсе, при шести
# появляется «Planet» против «Planeta», при двенадцати теряется верная. Взята
# середина полки.
#
# Порог от длины, а не числом: одна правка в шестибуквенном имени — это другое
# издательство, а в шестнадцатибуквенном — описка или другая схема
# транслитерации.
PER_EDIT = 8

# С какой длины имя разрешено узнавать по костяку согласных. Шесть — это
# `rosman`; на пяти и ниже правило начинает грозить настоящими короткими
# именами вроде «Дом» и «Дым», у которых костяк и число гласных совпадают, а
# издательства разные. Замерено 23.08.2026: на шести и ниже числа те же, на
# семи теряются две верные склейки, поэтому взята нижняя граница полки.
LEAST_BONES = 6

# Гласные латиницы: на них расходятся схемы транслитерации одного имени.
VOWELS = "aeiouy"


def named(raw: str) -> tuple[str, ...]:
    """Издательства, названные одной строкой. Их бывает несколько: «ЛитРес,
    АСТ» — это два разных издательства, решение пользователя 23.08.2026.

    Не режется строка, части которой связаны союзом: «Манн, Иванов и Фербер» —
    одно издательство из трёх фамилий, а не три. Отдельно стоящая форма
    собственности отбрасывается: «Бизнес-журнал, ЗАО» — одно имя.

    Цена названа трижды. Библиотечная запись «город : издатель» («N'iu-Iork :
    Izd-vo im. Chekhova») режется по двоеточию, и город становится
    издательством — одна строка из 260 в замере. Союз ищется во всей строке, и
    один союз отменяет разбор целиком: «ЛитРес, АСТ и Эксмо» останется одной
    студией. Косая черта режет: `Simon & Schuster/Paula Wiseman Books` — это
    импринт и его владелец, а `Bilingua/Билингва` — одно имя в двух
    письменностях, и там разбор спасает близость написаний, сводящая обе части
    в одну строку."""
    if not (raw or "").strip():
        return ()
    if _JOINED.search(raw):
        return (raw.strip(),)
    pieces = [one.strip() for one in _SEPARATORS.split(raw) if one.strip()]
    # Часть, от которой после приведения не осталось ничего, издательства не
    # называет: так отпадает форма собственности, стоящая отдельно
    # («Бизнес-журнал, ЗАО»). Проверяется тем же приведением, а не своим
    # списком, иначе два места знали бы одно и то же.
    kept = [one for one in pieces if publisher_key(one)]
    if kept:
        return tuple(kept)
    # Ничего не осталось — почему, решает вторая проверка. Имя из одной шелухи
    # («ООО», «Издательство») издательства не называет вовсе, и заводить под
    # него строку незачем. А имя, которого приведение не знает целиком —
    # «講談社», иврит, греческий, — называет, и вернуть его надо как есть.
    return () if any(_spelled(one) for one in pieces) else (raw.strip(),)


@lru_cache(maxsize=4096)
def publisher_key(name: str) -> str:
    """Написание, по которому одно издательство узнаётся в другом написании.

    Ответ запоминается: поиск близкого зовёт приведение на каждой строке
    таблицы студий и всякий раз заново приводит **спрошенное** имя. Памяти это
    стоит ключа на имя, а имён в базе тысячи.

    Наружу не показывается никогда: человек видит то, что прислал источник, а
    это — ключ сравнения."""
    latin = _spelled(name)
    if latin in KEPT_WHOLE:
        # У этого имени служебное слово своё, и снимать его нельзя.
        return latin
    return " ".join(one for one in latin.split()
                    if one not in FORMS and one not in WORDS)


def _spelled(name: str) -> str:
    """Имя одной письменностью и без обрамления — до снятия служебных слов.

    Своим шагом, потому что спрашивают его двое и о разном: ключ снимает с него
    шелуху, а `named` по нему отличает имя из одной шелухи («ООО») от имени,
    которого приведение не знает вовсе («講談社»). У первого здесь что-то есть,
    у второго пусто."""
    quoted = _QUOTED.search(name)
    spelled = _PARENS.sub(" ", quoted.group(1) if quoted else name)
    # Подмена смотрит на регистр, поэтому идёт до приведения к строчным.
    read = flattened(" ".join(_as_russian(one) for one in spelled.split()))
    return "".join(_TRANSLIT.get(one, one) for one in read)


def alike(first: str, second: str) -> bool:
    """Одно ли это издательство, написанное по-разному.

    Сравниваются приведённые написания, и не на равенство: транслитерация у
    одного имени бывает разной («Росмэн» — это и `Rosman`, и `Rossmen`), а
    описка — обычное дело. Считается расстояние Дамерау — Левенштейна: сколько
    вставок, удалений, замен и перестановок соседних букв отделяют одно
    написание от другого. Порог зависит от длины, см. `PER_EDIT`.

    Порядок проверок — про цену, а не про смысл. Спрашивают эту функцию на
    каждой строке таблицы студий (`credits.py:_written_alike`), а динамика
    расстояния стоит O(n·m) с выделением таблицы на пару: замерено ревью
    23.08.2026 — 180 мс на две тысячи строк, то есть почти вся цена поиска.
    Поэтому до неё стоят две отсечки, каждая линейная: равенство ключей и
    разница длин, которая одна уже больше порога."""
    left, right = publisher_key(first), publisher_key(second)
    if not left or not right:
        return False
    if left == right:
        return True
    limit = min(len(left), len(right)) // PER_EDIT
    if limit and not _too_far(left, right, limit) and _steps(left, right) <= limit:
        return True
    return _same_bones(left, right)


def _too_far(left: str, right: str, limit: int) -> bool:
    """Заведомо ли дальше порога — по одному составу букв, без динамики.

    Ни одна из правок Дамерау — Левенштейна не убирает больше одной непарной
    буквы с каждой стороны, а перестановка соседних не меняет состав вовсе.
    Значит непарных больше порога — расстояние тоже больше, и считать его
    незачем.

    Отсечка нужна цене: близость спрашивают на каждой строке таблицы студий, а
    динамика стоит O(n·m) с выделением таблицы на пару."""
    shared = sum((Counter(left) & Counter(right)).values())
    return max(len(left), len(right)) - shared > limit


def _same_bones(left: str, right: str) -> bool:
    """Одно ли это имя, записанное по другой схеме транслитерации.

    Смотрит на костяк согласных **при том же числе гласных**: у «Росмэн» есть
    и `Rosman`, и `Rossmen` — гласная **заменена**, костяк тот же. Добавленная
    гласная — уже другое имя: `Planet` против `Planeta`, и число гласных их
    разводит. Замерено 23.08.2026: с этим правилом 16 склеек из 18 при нуле
    ложных, без него 14.

    Первая гласная при этом обязана совпасть. Без неё правило меняет любую
    гласную на любую, и `Vintage Books` встаёт одной строкой с `Vantage Press` —
    поймано ревью 23.08.2026 перебором 107 имён, единственная ложная склейка на
    5671 пару. Схемы транслитерации расходятся на конце имени, а не на первом
    слоге: `Rosman` и `Rossmen` начинаются одинаково.

    Удвоенные буквы здесь схлопываются — но только для сравнения: `Rossmen` и
    `Rosman` одна и та же «с». Само написание не трогается никогда."""
    plain = (_DOUBLED.sub(r"\1", one) for one in (left, right))
    first, second = list(plain)
    if min(len(first), len(second)) < LEAST_BONES:
        return False
    bones = ["".join(c for c in one if c not in VOWELS) for one in (first, second)]
    vowels = ["".join(c for c in one if c in VOWELS) for one in (first, second)]
    return (bones[0] == bones[1]
            and len(vowels[0]) == len(vowels[1])
            and vowels[0][:1] == vowels[1][:1])


def _steps(first: str, second: str) -> int:
    """Расстояние Дамерау — Левенштейна. Своей реализацией, а не зависимостью:
    двадцать строк против пакета ради одной функции."""
    if first == second:
        return 0
    rows = [[0] * (len(second) + 1) for _ in range(len(first) + 1)]
    for i in range(len(first) + 1):
        rows[i][0] = i
    for j in range(len(second) + 1):
        rows[0][j] = j
    for i in range(1, len(first) + 1):
        for j in range(1, len(second) + 1):
            cost = 0 if first[i - 1] == second[j - 1] else 1
            rows[i][j] = min(rows[i - 1][j] + 1,
                             rows[i][j - 1] + 1,
                             rows[i - 1][j - 1] + cost)
            # Перестановка соседних букв — одна правка, а не две: `Rosnam`
            # против `Rosman` это описка, а не другое имя.
            if (i > 1 and j > 1 and first[i - 1] == second[j - 2]
                    and first[i - 2] == second[j - 1]):
                rows[i][j] = min(rows[i][j], rows[i - 2][j - 2] + cost)
    return rows[-1][-1]


def _as_russian(word: str) -> str:
    """Короткая аббревиатура капсом из одних букв-двойников читается
    по-русски. Условия и их цена — у `LOOKALIKE`."""
    if not word.isupper() or len(word) > _LOOKALIKE_LIMIT:
        return word
    lowered = word.lower()
    return (lowered.translate(_AS_CYRILLIC)
            if all(one in LOOKALIKE for one in lowered) else word)
