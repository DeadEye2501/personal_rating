"""Отказ, закрывающий источник на срок."""

from datetime import timedelta

from backend.model import Reason, Refusal
from backend.sources.http import SourceHttp


def refuse_until(http: SourceHttp, reason: Reason, delay: timedelta,
                 source: str | None = None) -> Refusal:
    """Взвести предохранитель и отказать тем же сроком.

    Заведено на шести копиях в пяти модулях: у MDBList по `Retry-After`, у OMDB
    до полуночи, у обоих зеркал Кинопоиска своими константами, у магазинов
    догадкой в пять минут, у TMDB её объявленной минутой. Сроки разные и
    правильно разные, а вот **срок, названный в отказе, обязан совпадать со
    сроком закрытия** — и этот инвариант не держало ничто: в каждой копии число
    писалось дважды, а у TMDB ещё и в двух разных функциях.

    `source` называется отдельно там, где источник назван собственной
    константой, а не именем соединения: у Кинопоиска это `SOURCE`, общий для
    обоих зеркал. Сегодня оба имени совпадают и подмена не наблюдалась бы, но
    имя соединения — дело сборки, а имя источника едет в плашку человеку.

    Живёт это отдельным модулем, а не в `http.py` рядом с самим предохранителем:
    транспорт ответы не классифицирует — какой код чем считать, знает только
    источник. И не в `errors.py`: там построители отказа без состояния, а этот
    закрывает источник, то есть меняет состояние транспорта.
    """
    http.breaker.trip(delay, reason)
    return Refusal(source=source or http.name, reason=reason, retry_after=delay)
