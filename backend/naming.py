"""Как имя пишется у нас.

Решение пользователя 23.08.2026: **первая буква заглавная у всего, что человек
читает** — название, оригинальное название, синопсис, имя человека, название
студии, трек, тег, рецензия. Правило одно на все пять типов содержимого.

Источник пишет как хочет, и это его дело: у Deezer исполнитель «жадный дельфин»
и альбом «консумерки» набраны строчными нарочно, у TMDB киношные жанры приходят
строчными, а сериальные с заглавной. Разноголосица чужих написаний в базу не
тащится — так же, как в справочнике жанров, где имена наши с самого начала.

Приводится при **записи**, а не при показе: в базе должно лежать то, что человек
видит, иначе поиск, сортировка и выгрузка расходятся с экраном.

Цена названа и принята: правило необратимо поднимает и стилизованное со
строчной — `iRacing` станет `IRacing`, `iowa` станет `Iowa`. Для карточки из
источника это лечится перезапросом, для заведённой руками — нет.

Лежит в корне пакета по тому же доводу, что `language` и `unique`: приём нужен и
хранилищу, и сервисам, а не одному слою. Зовут его пять репозиториев и
`service/hits.py` — строка выдачи ещё не записана, а показывается раньше всего.
"""

__all__ = ["capitalized"]


def capitalized(text: str) -> str:
    """Имя с заглавной первой буквы. Остальное — написание источника: `capitalize`
    из стандартной библиотеки не годится, он опускает весь хвост, и `HORROR
    VACUI` стал бы `Horror vacui`.

    Строка без первой заглавной возвращается той же самой, а не пересобранной:
    пересборка меняла бы байты у всех имён до единого, а меняться должны те, что
    правда написаны строчными."""
    if not text or text[0] == text[0].upper():
        return text
    return text[0].upper() + text[1:]
