"""Строка выдачи обязана знать, о чём её спросили.

Отдельно от склейки, хотя обе берут строку запроса: та сравнивает строки между
собой, эта — строку с запросом.

Нужен отсев потому, что у GOG нет понятия «не найдено»: на бессмыслицу он
отвечает двумя десятками несвязанных игр, и до этого правила они доезжали до
экрана. Замерено 03.08.2026 боевым кодом: на русском запросе мусора 94% от
показанного, на английском 23%.

Решение пользователя того же дня — «или адекватная выдача, или не быть вообще».
"""

from backend.model import Kind, SearchHit
from backend.service.titles import flattened

__all__ = ["relevant"]


def _asked(query: str) -> set[str]:
    """Значащие слова запроса.

    Число словом не считается: по «3» совпадает и «Ведьмак 3», и «Baldur's
    Gate 3», и «Broken Sword 3» — то есть что угодно. Свидетель снят с живого
    GOG 03.08.2026: по «fallout 2» он приносит `FlatOut 2`."""
    return {one for one in flattened(query).split() if not one.isdigit()}


def _knows(hit: SearchHit, asked: set[str]) -> bool:
    """Слова строки берутся оттуда же, откуда ключи склейки: показываемое
    название, второе название, псевдонимы.

    Без псевдонима `Кровная вражда: Ведьмак. Истории` выпала бы на запросе
    «witcher» — настоящая игра серии, показанная GOG под русским названием.
    Спасает её слаг, и это замерено."""
    for text in (hit.title, hit.original_title, *hit.aliases):
        if asked & set(flattened(text).split()):
            return True
    return False


def relevant(answers: list[list[SearchHit]],
             query: str) -> list[list[SearchHit]]:
    """Выдачи без строк, не знающих ни одного значащего слова запроса.

    Запрос без значащих слов не отсеивает ничего: пустой набор выбросил бы всё,
    а набрать одни цифры человек вправе.

    Зовётся **только на выдачи каталогов**. У работ тёзок запрос — это имя
    человека, а строки — его фильмы, и общего слова у «Джона Траволты» с
    «Криминальным чтивом» нет ни одного: общий отсев отменил бы поиск по имени
    целиком.

    **Кино и сериалы не трогает вовсе**, и это не перестраховка. Правило
    замерено на играх и держится их свойством: у GOG нет понятия «не найдено»,
    поэтому на бессмыслицу он отвечает чем попало. У TMDB оно есть, а сверх того
    он ищет по переводам и альтернативным названиям, которых в строке нет вовсе,
    и показываемое название приезжает по-русски. Замерено 03.08.2026 на живом
    API: по «the lives of others» из четырёх строк уцелела бы одна, и не та, а у
    «Унесённых призраками» оригинал `千と千尋の神隠し` — приведение даёт пустую
    строку, то есть знать запрос ей нечем в принципе. Тем же способом и по тому
    же доводу из склейки исключено кино.

    Выдачи остаются выдачами: порядок внутри каждой задал источник, а по ним
    потом идёт переплетение."""
    asked = _asked(query)
    if not asked:
        return answers
    if not all(one.kind is Kind.GAME for answer in answers for one in answer):
        return answers
    return [[one for one in answer if _knows(one, asked)] for answer in answers]
