"""Строка выдачи обязана знать, о чём её спросили.

Отдельно от склейки, хотя обе берут строку запроса: та сравнивает строки между
собой, эта — строку с запросом.

Нужен отсев потому, что у GOG нет понятия «не найдено»: на бессмыслицу он
отвечает двумя десятками несвязанных игр, и до этого правила они доезжали до
экрана. Замерено 03.08.2026 боевым кодом: на русском запросе мусора 94% от
показанного, на английском 23%.

Решение пользователя того же дня — «или адекватная выдача, или не быть вообще».
"""

from backend.model import Kind, SearchHit
from backend.titles import flattened

__all__ = ["relevant"]

# Кому отсев нужен: тем источникам, у которых нет понятия «не найдено». У GOG
# его нет вовсе, у Google Books `totalItems` всегда 300 — на любой запрос
# найдётся триста книг, и чем глубже страница, тем меньше в ней запроса.
_ASKED_STRICTLY = frozenset({Kind.GAME, Kind.BOOK})


def _asked(query: str) -> set[str]:
    """Слова запроса. Цифры наравне с текстом: они сужают, а не шумят.

    Решение пользователя 03.08.2026 — «Герои» находят все части, «Герои 3»
    только третью. Оно же чинит `Heroes of Might and Magic: Olden Era`, которая
    иначе выходит первой строкой на запрос про третьих: все текстовые слова у
    неё есть, а игра другая."""
    return set(flattened(query).split())



def _knows(hit: SearchHit, asked: set[str]) -> bool:
    """Знает ли строка **все** слова запроса.

    Все, а не хоть одно: с «хоть одним» по «x com» пролезало 14 строк из 68, а
    `s.t.a.l.k.e.r` приведение режет на семь однобуквенных слов — и проходила
    любая строка с буквой `s` в названии. Замерено 03.08.2026.

    Слова берутся оттуда же, откуда ключи склейки: показываемое название, второе
    название, псевдонимы, — и складываются в одну кучу: одно слово запроса может
    найтись в названии, другое в слаге. Без псевдонима `Кровная вражда: Ведьмак.
    Истории` выпала бы на запросе «witcher», а это настоящая игра серии,
    показанная GOG под русским названием.

    **Форма на `s` считается тем же словом**, и это не вольность, а плата за
    приведение: апостроф оно съедает, `Baldur's` становится `baldurs`, и запрос
    «baldur» не находил ничего — 19 строк на входе, ноль на экране.

    Совпадение началом слова замерено и отвергнуто: по «x com» оно пропускает 62
    строки из 68."""
    have: set[str] = set()
    for text in (hit.title, hit.original_title, *hit.aliases):
        have |= set(flattened(text).split())
    return all(one in have or one + "s" in have for one in asked)



def relevant(answers: list[list[SearchHit]],
             query: str) -> list[list[SearchHit]]:
    """Выдачи без строк, не знающих всех слов запроса.

    Пустой запрос не отсеивает ничего: пустой набор слов выбросил бы всё.

    Зовётся **только на выдачи каталогов**. У работ тёзок запрос — это имя
    человека, а строки — его фильмы, и общего слова у «Джона Траволты» с
    «Криминальным чтивом» нет ни одного: общий отсев отменил бы поиск по имени
    целиком.

    **Книги отсеиваются наравне с играми** — решение пользователя 23.08.2026,
    «если я ищу властелина колец, то я должен получить властелина колец». Болезнь
    у Google Books та же, что у GOG: `totalItems` он отдаёт всегда 300, и на
    третьей странице по «властелин колец» приезжают «Семья и школа» и
    библиографические указатели. Цена замерена в тот же день на живой выдаче: из
    шестидесяти строк остаётся шесть, и вместе с мусором уходят «Хранители
    кольца» и транслитерация «Vlastelin Kolec» — слов запроса в них нет.

    **Кино и сериалы не трогает вовсе**, и это не перестраховка. Правило
    замерено на играх и держится их свойством: у GOG нет понятия «не найдено»,
    поэтому на бессмыслицу он отвечает чем попало. У TMDB оно есть, а сверх того
    он ищет по переводам и альтернативным названиям, которых в строке нет вовсе,
    и показываемое название приезжает по-русски. Замерено 03.08.2026 на живом
    API: по «the lives of others» из четырёх строк уцелела бы одна, и не та, а у
    «Унесённых призраками» оригинал `千と千尋の神隠し` — приведение даёт пустую
    строку, то есть знать запрос ей нечем в принципе. Тем же способом и по тому
    же доводу из склейки исключено кино.

    Выдачи остаются выдачами: порядок внутри каждой задал источник, а по ним
    потом идёт переплетение."""
    asked = _asked(query)
    if not asked:
        return answers
    if not all(one.kind in _ASKED_STRICTLY
               for answer in answers for one in answer):
        return answers
    return [[one for one in answer if _knows(one, asked)] for answer in answers]
