"""Заведение карточки в обоих файлах базы.

Отдельным модулем, а не методом репозитория: репозиторий владеет одним файлом
базы, и требовать от вызывающего второе хранилище значило бы гнать через границу
слоёв объект с открытым движком. Тот же довод, что у `service/removal.py`, и
порядок тут обратный: там обложка уходит первой, здесь — следом за номером.
"""

import asyncio
import logging

from backend.model import Item
from backend.service.posters import PosterService
from backend.storage.repository.library import LibraryRepository

logger = logging.getLogger(__name__)


async def fresh_item(library: LibraryRepository, posters: PosterService,
                     item: Item) -> int:
    """Новая строка карточки — и заведомо пустое место под её обложку.

    Уборка нужна потому, что `id` карточки SQLite выдаёт повторно: `item`
    заведён без `AUTOINCREMENT`, и удалённый номер достаётся следующей карточке.
    Обложка при этом лежит во втором файле базы, где внешних ключей не бывает, и
    пережить свою карточку она может: скачивание живёт до двадцати секунд, и
    доехавшие байты записываются уже после удаления. Найденную в хранилище
    обложку никто не перекачивает — чужая осталась бы навсегда.

    Гонку это закрывает не целиком: обложка способна доехать и после заведения
    новой карточки. Закрыто окно между удалением старой и заведением новой — то,
    где сирота живёт долго и попадает на глаза.

    За собой убирает сам: строка уже закоммичена, а уборка — второй заход в
    базу, и сорваться он может отменой или занятым файлом хранилища. Иначе в
    базе осталась бы строка со свежим `synced_at`, без жанров, состава и
    обложки, — та самая частичная карточка, которой «не бывает». Откат снаружи
    тут не поможет: у писателя он начинается там, где строка уже заведена."""
    item_id = await library.create(item)
    try:
        await posters.delete(item_id)
    except asyncio.CancelledError:
        # Отмена в `Exception` не попадает — она наследник `BaseException`, — а
        # приходит она штатно: так гасится загрузка при закрытии окна.
        logger.warning("заведение карточки %s отменено, откатываю", item_id)
        await library.delete(item_id)
        raise
    except Exception:
        logger.exception("откатываю карточку %s: обложка не убралась", item_id)
        await library.delete(item_id)
        raise
    return item_id
