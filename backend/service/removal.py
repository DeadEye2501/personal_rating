"""Удаление карточки из обоих файлов базы, двумя путями.

Путей два, и разница не косметическая: решение человека помнится, откат
сорвавшейся записи — нет. Что из этого следует, записано у самих функций."""

from backend.service.posters import PosterService
from backend.storage.repository.library import LibraryRepository
from backend.storage.repository.removed import RemovedRepository


async def discard_card(library: LibraryRepository, posters: PosterService,
                       removed: RemovedRepository, item_id: int) -> None:
    """Человек убрал карточку: она уходит и больше не приходит.

    Отдельно от `remove_card`, и разница не косметическая. Тот же порядок
    удаления зовёт откат сорвавшейся записи, а откат — не решение человека:
    пометь его, и игра, которая просто не сохранилась из-за обрыва сети,
    перестала бы находиться навсегда.

    Память пишется **до** удаления: после него источник и название взять негде.
    Общей транзакции у шагов не бывает — постер лежит во втором файле базы, —
    поэтому порядок выбран по тому, чем оборачивается обрыв. Здесь карточка
    останется в библиотеке, а её строка пропадёт из внешней выдачи: второе
    нажатие доведёт дело до конца. В обратном порядке карточки уже не было бы, а
    убранное вернулось бы следующим же поиском, и понять почему было бы нечем."""
    item = await library.get(item_id)
    if item is not None:
        await removed.remember(item)
    await remove_card(library, posters, item_id)


async def remove_card(library: LibraryRepository, posters: PosterService,
                      item_id: int) -> None:
    """Оценка, теги, закладка и связи уходят каскадом; постер — кодом: внешних
    ключей между двумя файлами SQLite не бывает.

    Постер уходит первым, и порядок здесь не косметика. Оборвись удаление на
    середине — у обратного порядка в хранилище остался бы постер без хозяина, а
    `id` карточки SQLite выдаёт повторно: `item` заведён без `AUTOINCREMENT`, и
    следующая карточка молча получила бы чужую обложку. В этом порядке остаётся
    карточка без обложки, а её скачают заново по `poster_url` при первом показе.

    Отдельным модулем, а не методом репозитория: репозиторий владеет одним файлом
    базы, и требовать от вызывающего второе хранилище значило бы гнать через
    границу слоёв объект с открытым движком. Зовут отсюда двое — откат записи и
    удаление по кнопке, — и порядок обоим нужен один и тот же.

    **Память об убранном сюда не входит, и это не упущение.** Зовут отсюда двое,
    и значат они разное: человек нажал «удалить» — игру больше не показывать;
    писатель откатывает сорвавшуюся запись — карточка не сохранилась, и закрыть
    ей дорогу назад было бы прямой поломкой, найти её стало бы нельзя никогда.
    Помнит убранное тот, кто знает, что это было решение человека, — сосед
    сверху, `discard_card`; его и зовёт кнопка удаления."""
    await posters.delete(item_id)
    await library.delete(item_id)
